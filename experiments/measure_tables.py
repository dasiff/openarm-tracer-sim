"""Tables for the SF-123 measure-the-sag test copy (analysis only; reads the saved run folders, loads no simulator).

    python experiments/measure_tables.py --root data/logs/stage2j --out data/logs/stage2j/tables.md

One table per T (0.25, 0.5, 1, 2 s), with the production layer ("integ") as the comparison row. Policy rows: dq peak and final per joint (mrad),
ticks at the clip, hand error on versus off. Static rows: the estimate against the droop at each pose, the settle time. Held-still rows: the
bounded control and the unreachable variant. Teleop rows: hand error and dq peak (the hand error needs the simulator, see teleop_hand_error).
"""

import argparse
import json
import re
from pathlib import Path

import numpy as np

RULES = [("integ", "production (integrator)"), ("meas_T0.25", "measure, T=0.25 s"), ("meas_T0.5", "measure, T=0.5 s"),
         ("meas_T1", "measure, T=1 s"), ("meas_T2", "measure, T=2 s")]


def policy_row(root, variant, tag):
    d = Path(root) / f"policy_{variant}_{tag}"
    npz = d / "run.npz"
    if not npz.exists():
        return None
    z = np.load(npz)
    dq = z["left_dq"][:, :7]
    t = z["left_t"]
    scale = z["left_scale"]
    final = dq[t >= t[-1] - 2.0].mean(axis=0)
    peak = np.max(np.abs(dq), axis=0)
    clip = int(np.sum(scale < 1.0)) if tag != "integ" else None
    js = list(d.glob(f"{variant}_s1_*_nobridge.json"))
    on = next((json.load(open(j)) for j in js if "_on_" in j.name), None)
    off = next((json.load(open(j)) for j in js if "_off_" in j.name), None)
    if clip is None and on is not None:
        clip = on["position"]["ticks_at_clip"] + on["rotation"]["ticks_at_clip"]
    return {"peak": peak * 1e3, "final": final * 1e3, "clip": clip,
            "hand_on": on["hand_error_m"]["mean"] * 1e3 if on else None,
            "hand_off": None}


def policy_off_hand(root, variant):
    d = Path(root) / f"policy_{variant}_off"
    js = list(d.glob(f"{variant}_s1_off_nobridge.json"))
    return json.load(open(js[0]))["hand_error_m"]["mean"] * 1e3 if js else None


def cmd_tables(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    root = Path(a.root)
    lines = ["# SF-123 test copy: measure-the-sag, tables (generated by experiments/measure_tables.py)", ""]
    lines.append("## Policy A, B, C (seed 1), bridge off, nominal physics")
    lines.append("")
    for tag, label in RULES:
        lines.append(f"### {label}")
        lines.append("")
        lines.append("| variant | dq peak per joint (mrad) | dq final per joint (mrad) | ticks at clip | hand error on (mm) | hand error off (mm) |")
        lines.append("|---|---|---|---|---|---|")
        for v in "ABC":
            r = policy_row(root, v, tag)
            if r is None:
                lines.append(f"| {v} | not run | | | | |")
                continue
            off = policy_off_hand(root, v)
            lines.append(f"| {v} | {np.round(r['peak'], 1).tolist()} | {np.round(r['final'], 1).tolist()} | {r['clip']} | "
                         f"{r['hand_on']:.2f} | {off:.2f} |" if r["hand_on"] is not None and off is not None else f"| {v} | {np.round(r['peak'], 1).tolist()} | {np.round(r['final'], 1).tolist()} | {r['clip']} | - | - |")
        lines.append("")
    lines.append("## Held-still zero-mean control (bounded) and unreachable variant (informational)")
    lines.append("")
    lines.append("| rule | zero-mean: max \\|C_p\\| (mm) | max \\|C_r\\| (mrad) | growth late | unreachable: max \\|C_p\\| (mm) | max \\|C_r\\| (mrad) |")
    lines.append("|---|---|---|---|---|---|")
    for tag, label in RULES:
        zm = root / f"heldstill_{tag}_zeromean.json"
        ur = root / f"heldstill_{tag}_unreachable.json"
        if not zm.exists():
            lines.append(f"| {label} | not run | | | | |")
            continue
        z = json.load(open(zm))
        u = json.load(open(ur)) if ur.exists() else {"max_C_p_mm": float("nan"), "max_C_r_mrad": float("nan")}
        lines.append(f"| {label} | {z['max_C_p_mm']} | {z['max_C_r_mrad']} | {z['growth_late']} | {u['max_C_p_mm']} | {u['max_C_r_mrad']} |")
    lines.append("")
    lines.append("## Five poses, perturbed physics, correction on: estimate against droop, settle time")
    lines.append("")
    for tag, label in RULES:
        md = root / f"static_{tag}.md"
        lines.append(f"### {label}")
        lines.append("")
        if not md.exists():
            lines.append("not run")
            lines.append("")
            continue
        lines += [ln for ln in md.read_text().splitlines() if ln.startswith("- ")]
        lines.append("")
    Path(a.out).write_text("\n".join(lines) + "\n")
    print(f"measure_tables: wrote {a.out}")


if __name__ == "__main__":
    import sys
    cmd_tables(sys.argv[1:])
