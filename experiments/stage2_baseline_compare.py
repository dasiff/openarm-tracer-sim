"""Baseline differences for the stage 2 report (David d0bc 2026-11-24, report only): the bench CSVs of one scenario from two code states, row by row.
Per scenario: the largest difference of each joint column (degrees, with the sim time it happens at) and the largest difference of the pad position
of each hand (mm). The hand position is the pad's forward kinematics from the joint columns in the robot's own base frame (the base pose and the
pedestal are not used, so the number isolates the arm joints).

    python experiments/stage2_baseline_compare.py --root data/logs/rebuild_s2/baseline --out data/logs/rebuild_s2/baseline/compare.md
"""

import argparse
import csv
import os
import sys
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))
os.environ.setdefault("MUJOCO_GL", "egl")

PAIRS = [("stage2", "5e6d7be"), ("stage2", "1f29da7"), ("5e6d7be", "1f29da7")]
SCENARIOS = ["manual", "teleop", "policy"]
JOINT_COLS = [f"{s}_joint{j}" for s in ("left", "right") for j in range(1, 8)]


def load(path):
    rows = list(csv.DictReader(open(path)))
    return rows


def pad_positions(model, data, layers, rows):
    """Pad centre (mm, base frame) of each hand for each row: arrays (n, 2, 3)."""
    import mujoco
    out = np.zeros((len(rows), 2, 3))
    for i, r in enumerate(rows):
        for si, (s, layer) in enumerate(layers):
            q = np.radians([float(r[f"{s}_joint{j}"]) for j in range(1, 8)])
            data.qpos[layer.arm.qadr] = q
        mujoco.mj_forward(model, data)
        for si, (s, layer) in enumerate(layers):
            p, _ = layer.arm.pad_pose(data)
            out[i, si] = 1e3 * np.asarray(p, float)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    import mujoco
    from src.sag_layer import _PadGeometry

    model = mujoco.MjModel.from_xml_path(str(REPO / "models" / "robot" / "combined_robot.xml"))
    data = mujoco.MjData(model)
    from src.robot_helpers import arm_ids

    class _L:
        pass
    layers = []
    for s in ("left", "right"):
        L = _L()
        L.arm = _PadGeometry(model, s)
        layers.append((s, L))
    root = Path(a.root)
    lines = ["# Baseline differences (generated by experiments/stage2_baseline_compare.py; report only)", "",
             "Pairs: stage 2 code against HEAD before this round (5e6d7be) and against HEAD before stage 1 (1f29da7); and 5e6d7be against 1f29da7 for "
             "context. Joint columns in degrees; hand position in mm from the pad's forward kinematics in the robot base frame.", ""]
    for scen in SCENARIOS:
        lines += [f"## {scen}", "", "| pair | rows | largest joint difference (deg) | joint, sim time | largest hand position difference (mm) | hand, sim time |",
                  "|---|---|---|---|---|---|"]
        for new, old in PAIRS:
            fn, fo = root / new / f"{scen}.csv", root / old / f"{scen}.csv"
            if not fn.exists() or not fo.exists():
                lines.append(f"| {new} vs {old} | not run | | | | |")
                continue
            rn, ro = load(fn), load(fo)
            n = min(len(rn), len(ro))
            if len(rn) != len(ro):
                lines.append(f"| {new} vs {old} | row counts differ ({len(rn)} vs {len(ro)}) | | | | |")
                continue
            t = np.array([float(r["sim_time"]) for r in rn[:n]])
            best = (0.0, "", 0.0)
            for c in JOINT_COLS:
                d = np.abs(np.array([float(r[c]) for r in rn[:n]]) - np.array([float(r[c]) for r in ro[:n]]))
                k = int(np.argmax(d))
                if d[k] > best[0]:
                    best = (float(d[k]), f"{c}", float(t[k]))
            pn = pad_positions(model, data, layers, rn[:n])
            po = pad_positions(model, data, layers, ro[:n])
            dd = np.linalg.norm(pn - po, axis=2)           # (n, 2): per hand
            kh, sh = np.unravel_index(int(np.argmax(dd)), dd.shape)
            hand = "left" if sh == 0 else "right"
            lines.append(f"| {new} vs {old} | {n} | {best[0]:.3f} | {best[1]} at {best[2]:.2f} s | {dd.max():.3f} | {hand} hand at {t[kh]:.2f} s |")
        lines.append("")
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text("\n".join(lines) + "\n")
    print(f"stage2_baseline_compare: wrote {a.out}")


if __name__ == "__main__":
    main()
