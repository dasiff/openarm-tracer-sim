"""Hand movement in the 5 s after the open-catch release, in the held run (stage 2, David 2026-11-24, decision 2). Analysis only: forward kinematics
of the left pad from the logged joints (one MuJoCo model, no simulation).

    python experiments/stage2_release_report.py --trace nominal=DIR/trace.npz:DIR/run.log --trace perturbed=DIR2/trace.npz:DIR2/run.log --out OUT.md

The release time is the sag layer's release event in the run log ("release_done t=..."), i.e. the completion of the open-catch release. The
window is 5 s after it. Reported: the pad's movement from its position at the release (largest in the window, and at the end), the path length,
the learned offset |C_p| at the release and at the end, and whether the estimate was reset (it is not, decision 2: checked on the logged offset).
"""

import argparse
import re
import sys
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))
WINDOW_S = 5.0


def release_time(log_path):
    txt = Path(log_path).read_text(errors="replace")
    m = re.findall(r"release_(?:done|reset) t=([\d.]+)", txt)
    return float(m[0]) if m else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--trace", action="append", required=True, help="label=trace.npz:run.log")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    import mujoco
    from src.sag_layer import _PadGeometry

    model = mujoco.MjModel.from_xml_path(str(REPO / "models" / "robot" / "combined_robot.xml"))
    data = mujoco.MjData(model)
    geo = _PadGeometry(model, "left")
    lines = ["# Held run: hand movement in the 5 s after the open-catch release (generated by experiments/stage2_release_report.py)", "",
             "| run | release at (s) | pad at release (mm, base frame) | largest movement in 5 s (mm) | movement at 5 s (mm) | path length in 5 s (mm) | "
             "|C_p| at release (mm) | |C_p| at 5 s (mm) | samples |", "|---|---|---|---|---|---|---|---|---|"]
    for spec in a.trace:
        label, rest = spec.split("=", 1)
        npz, log = rest.split(":", 1)
        tr = np.load(npz, allow_pickle=True)
        t = tr["left_t"]
        q = tr["left_q"]
        cp = np.linalg.norm(tr["left_C_p"], axis=1) if "left_C_p" in tr.files else np.full(len(t), np.nan)
        tr_release = release_time(log)
        if tr_release is None:
            lines.append(f"| {label} | not found in the log | | | | | | | |")
            continue
        qadr = geo.qadr
        pads = []
        for k in range(len(t)):
            data.qpos[qadr] = q[k, qadr]
            mujoco.mj_forward(model, data)
            p, _ = geo.pad_pose(data)
            pads.append(1e3 * np.asarray(p, float))
        pads = np.array(pads)
        k0 = int(np.searchsorted(t, tr_release))
        k1 = int(np.searchsorted(t, tr_release + WINDOW_S))
        k1 = min(k1, len(t) - 1)
        if k1 <= k0:
            lines.append(f"| {label} | {tr_release:.2f} | | | | | | | 0 |")
            continue
        seg = pads[k0:k1 + 1]
        d = np.linalg.norm(seg - seg[0], axis=1)
        path = float(np.sum(np.linalg.norm(np.diff(seg, axis=0), axis=1)))
        lines.append(f"| {label} | {tr_release:.2f} | ({seg[0][0]:.1f}, {seg[0][1]:.1f}, {seg[0][2]:.1f}) | {d.max():.2f} | {d[-1]:.2f} | "
                     f"{path:.2f} | {1e3 * cp[k0]:.3f} | {1e3 * cp[k1]:.3f} | {k1 - k0 + 1} |")
    lines.append("")
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text("\n".join(lines) + "\n")
    print(f"stage2_release_report: wrote {a.out}")


if __name__ == "__main__":
    main()
