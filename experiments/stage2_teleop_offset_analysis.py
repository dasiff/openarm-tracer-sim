"""Analysis of the teleop offset after motion stops (stage 2 follow-up, David 2026-11-25, item 1). Analysis only: reads saved traces and
computes the pad and its Jacobian from the joints (one MuJoCo model, no simulation).

    python experiments/stage2_teleop_offset_analysis.py teleop --run DIR/teleop_on/run.npz --off DIR/teleop_off/run.npz --out OUT.md
    python experiments/stage2_teleop_offset_analysis.py moves --root DIR/move --out OUT.md
    python experiments/stage2_teleop_offset_analysis.py replay --root DIR/move --static DIR/static/trace/trace.npz --droops static_droops.json --out OUT.md
    python experiments/stage2_teleop_offset_analysis.py policy --b DIR/policy/B/trace.npz --c DIR/policy/C/trace.npz --out OUT.md

Definitions. Pad: the left hand's pad centre (the layer's own pad geometry). Hand error: the pad of the reference (the bridge's accepted target, output
minus dq, the layer's stored reference) minus the pad of the measured joints. Hand-space offset: J(q) times the joint estimate (the pad move the
estimate causes at the current pose). Replay: the estimate's low-pass (T = 2 s) run again on the logged measured sag, with each tick's sag weighted
by w = 1 / (1 + (speed_j / s0)^2) per joint (speed from the measured joints); no layer change, and the closed loop is NOT re-simulated, so the replayed
hand errors are an approximation (the at-rest residual the replayed estimate would leave), labelled as such.
"""

