def pad_and_jac(q7):
    """Pad centre (m, base frame) and the 6 x 7 pad Jacobian at the left arm's joints q7."""
    _setup()
    mj, model, data, geo = _M["mujoco"], _M["model"], _M["data"], _M["geo"]
    data.qpos[_M["qadr"]] = np.asarray(q7, float)
    mj.mj_forward(model, data)
    p, _ = geo.pad_pose(data)
    jp = np.zeros((3, model.nv))
    jr = np.zeros((3, model.nv))
    mj.mj_jac(model, data, jp, jr, np.asarray(p, float), geo.tcp)
    return np.asarray(p, float), np.vstack([jp[:, geo.vadr], jr[:, geo.vadr]])


