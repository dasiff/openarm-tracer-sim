def estimates_at_stops(d, stops):
    """Hand-space estimate (mm) at each stop, from the call records (the left arm's estimate and joints)."""
    global _QADR_SCENE
    c = np.load(d / "calls.npz", allow_pickle=True)
    t = c["left_t"]
    qfull = c["left_q"]
    est = c["left_est"]
    t0 = float(t[0])
    if "_QADR_SCENE" not in globals() or _QADR_SCENE is None:
        _QADR_SCENE = scene_qadr()
    out = []
    for ts in stops:
        k = min(int(np.searchsorted(t, t0 + ts)), len(t) - 1)
        q7 = qfull[k, _QADR_SCENE]
        _, J = pad_and_jac(q7)
        out.append(float(np.linalg.norm(J[:3] @ est[k])) * 1e3)
    return out


_QADR_SCENE = None


def replay_weights(q7_seq, dt, s0):
    v = np.zeros_like(q7_seq)
    v[1:] = (q7_seq[1:] - q7_seq[:-1]) / dt
    if s0 is None:
        return np.ones_like(q7_seq)
    return 1.0 / (1.0 + (v / s0) ** 2)


def replay_est(sag, updated, q7_seq, dt, s0):
    """The estimate's low-pass run again on the logged sag (the updated ticks only), weighted per joint if s0 is given."""
    w = replay_weights(q7_seq, dt, s0)
    est = np.zeros(7)
    out = np.zeros((len(sag), 7))
    for k in range(len(sag)):
        if updated[k] and np.all(np.isfinite(sag[k])):
            est = est + (dt / T_LOW) * w[k] * (sag[k] - est)
        out[k] = est
    return out


def cmd_replay(a):
    root = Path(a.root)
    res = ["# Offline replay of the estimate with a speed weight (generated by experiments/stage2_teleop_offset_analysis.py replay)", "",
           "The current rule (weight 1) is checked first: the replay on the logged sag must reproduce the logged estimate. Then the same replay with "
           "w = 1/(1+(speed/s0)^2) per joint. The hand error in the table is an APPROXIMATION: the at-rest residual |droop - J est| the replayed "
           "estimate would leave at that time, with the logged measurements held fixed (no closed loop).", ""]
    global _QADR_SCENE
    if _QADR_SCENE is None:
        _QADR_SCENE = scene_qadr()
    for d in sorted(root.glob("v*_nominal_on")) + sorted(root.glob("v*_perturbed_on")):
        c = np.load(d / "calls.npz", allow_pickle=True)
        t = c["left_t"]
        qf = c["left_q"][:, _QADR_SCENE]
        sag = c["left_sag"]
        est_log = c["left_est"]
        upd = c["left_skip"] == 0
        dt = NOMINAL
        r1 = replay_est(sag, upd, qf, dt, None)
        err1 = float(np.max(np.abs(r1 - est_log)))
        res.append(f"## {d.name}: replay with weight 1 vs the logged estimate: largest difference {err1:.2e} rad (should be about 0)")
        res.append("")
        sched = json.loads((d / "move" / "schedule.json").read_text())
        stops = _stop_indices(sched)
        t0 = float(t[0])
        ks = [min(int(np.searchsorted(t, t0 + ts)), len(t) - 1) for ts in stops]
        res.append("| s0 (rad/s) | stop | estimate at the stop, hand space (mm) | at-rest droop (mm) | approx. residual at 0.5 s (mm) | at 1 s (mm) | at 2 s (mm) |")
        res.append("|---|---|---|---|---|---|---|")
        for s0 in (None,) + S0:
            r = replay_est(sag, upd, qf, dt, s0)
            label = "current (1)" if s0 is None else str(s0)
            for i, (ts, k) in enumerate(zip(stops, ks)):
                _, J = pad_and_jac(qf[k])
                eh = float(np.linalg.norm(J[:3] @ r[k])) * 1e3
                droop = droop_mm(d, i)
                # approximation (scalar, no closed loop): |droop - |J est(t)||, with the droop's size from the correction-off run
                resid = []
                for x in STOP_CHECKS:
                    kk = min(int(np.searchsorted(t, t0 + ts + x)), len(t) - 1)
                    _, J2 = pad_and_jac(qf[kk])
                    hand_est = float(np.linalg.norm(J2[:3] @ r[kk])) * 1e3
                    resid.append(float("nan") if droop is None else abs(droop - hand_est))
                dr = "" if droop is None else f"{droop:.2f}"
                res.append(f"| {label} | {i + 1} | {eh:.2f} | {dr} | {resid[0]:.2f} | {resid[1]:.2f} | {resid[2]:.2f} |")
        res.append("")
    st = np.load(a.static, allow_pickle=True)
    side = st["side"] if "side" in st.files else None
    m = (side == "left") if side is not None else np.ones(len(st["t"]), bool)
    sag = st["last_sag"][m]
    est_log = st["est"][m]
    qm = st["q_meas"][m]
    tt = st["t"][m]
    skips = [json.loads(s) for s in st["skip"][m]]
    upd = np.ones(len(sag), bool)
    before = 0
    for i_, sk in enumerate(skips):                     # the skip counts are cumulative: a call skipped the update if its count rose
        after = sum(sk.values())
        upd[i_] = (after == before)
        before = after
    res.append("## Five static holds (perturbed physics, correction on): replay against the at-rest droop")
    res.append("")
    dr = json.loads(Path(a.droops).read_text()) if a.droops else {}
    names = ["home", "pick", "policy B 7.4 s", "policy B 13.4 s", "policy B 21.4 s"]
    stop_idx = [600, 750, 1500, 2250, 3000]
    for s0 in (None,) + S0:
        r = replay_est(sag, upd, qm, NOMINAL, s0)
        label = "current (1)" if s0 is None else str(s0)
        res.append(f"### weight {label}")
        res.append("")
        res.append("| pose | stop (call) | estimate at the stop, hand space (mm) | at-rest droop (mm) |")
        res.append("|---|---|---|---|")
        for i_, name in enumerate(names):
            k = min(stop_idx[i_], len(r) - 1)
            _, J = pad_and_jac(qm[k])
            eh = float(np.linalg.norm(J[:3] @ r[k])) * 1e3
            res.append(f"| {name} | {k} | {eh:.2f} | {dr.get(name, float('nan')):.2f} |")
        res.append("")
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(res) + "\n")
    print(f"replay analysis: wrote {out}")


def droop_mm(d, i):
    """The at-rest droop of stop i for that speed and physics: from the correction-off run of the same set."""
    name = d.name.replace("_on", "_off")
    p = d.parent / name / "move" / "move.npz"
    if not p.exists():
        return None
    mv = np.load(p)
    sched = json.loads((d.parent / name / "move" / "schedule.json").read_text())
    ts = sched["stops"][i]["t"]
    kk = min(int(np.searchsorted(mv["t"], ts + 2.0)), len(mv["t"]) - 1)
    return float(np.linalg.norm(mv["herr"][kk])) * 1e3


def cmd_policy(a):
    lines = ["# Policies B and C (bridge on, correction on): does the offset build up when the motion slows? (generated by experiments/stage2_teleop_offset_analysis.py policy)",
             "", "A slowdown: the source's joint speed falls below 0.05 rad/s after being above 0.2 rad/s within the 0.3 s before. For each slowdown the hand-space "
             "estimate (J est) and the prediction error (predicted minus measured) are read at 0.5 s before and 1 s after it.", ""]
    _setup()
    for name in ("b", "c"):
        p = getattr(a, name)
        if not p or not Path(p).exists():
            lines.append(f"- {name.upper()}: not found")
            continue
        z = np.load(p, allow_pickle=True)
        t = z["t"]
        qsrc = z["q_src"]
        qm = z["q_meas"]
        est = z["est"]
        pred = z["pred"]
        side = z["side"] if "side" in z.files else None
        m = (side == "left") if side is not None else np.ones(len(t), bool)
        t, qsrc, qm, est, pred = t[m], qsrc[m], qm[m], est[m], pred[m]
        dt = np.r_[NOMINAL, np.diff(t)]
        vs = np.zeros(len(t))
        vs[1:] = np.linalg.norm((qsrc[1:] - qsrc[:-1]) / np.maximum(dt[1:], 1e-9)[:, None], axis=1)
        vs = np.convolve(vs, np.ones(10) / 10, mode="same")
        events = []
        last = -10
        for k in range(len(t)):
            if vs[k] < 0.05 and np.max(vs[max(k - 45, 0):k + 1]) > 0.2 and (k - last) > 150:
                events.append(k)
                last = k
        lines += [f"## Policy {name.upper()} (seed 1): {len(events)} slowdowns in {t[-1] - t[0]:.1f} s", ""]
        if not events:
            lines += ["No slowdown below 0.05 rad/s after 0.2 rad/s in this run (the source's path does not stop).", ""]
            continue
        lines += ["| slowdown at (s) | source speed before (rad/s) | J est, 0.5 s before (mm) | J est, 1 s after (mm) | change (mm) | prediction error 0.5 s before / 1 s after (deg) |",
                  "|---|---|---|---|---|---|"]
        chg = []
        for k in events:
            kb = max(int(np.searchsorted(t, t[k] - 0.5)), 0)
            ka = min(int(np.searchsorted(t, t[k] + 1.0)), len(t) - 1)
            _, Jb = pad_and_jac(qm[kb])
            _, Ja = pad_and_jac(qm[ka])
            eb = float(np.linalg.norm(Jb[:3] @ est[kb])) * 1e3
            ea = float(np.linalg.norm(Ja[:3] @ est[ka])) * 1e3
            pb = float(np.degrees(np.linalg.norm(pred[kb] - qm[kb])))
            pa = float(np.degrees(np.linalg.norm(pred[ka] - qm[ka])))
            chg.append(ea - eb)
            lines.append(f"| {t[k]:.2f} | {float(np.max(vs[max(k - 45, 0):k + 1])):.2f} | {eb:.3f} | {ea:.3f} | {ea - eb:+.3f} | {pb:.3f} / {pa:.3f} |")
        lines += ["", f"Mean change of the hand-space estimate across the slowdowns: {np.mean(chg):+.3f} mm (n = {len(chg)}).", ""]
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print(f"policy analysis: wrote {out}")


def cmd_teleop_replay(a):
    """Replay of the estimate on the logged teleop sag (item 1d for the teleop run). The layer updates on the ticks where its sag changes (no
    arm command, no update: the logged sag is constant then). Droop: the teleop run's correction-off hand error 1 s after the same stop."""
    z = np.load(a.run, allow_pickle=True)
    t = z["t"]
    q = z["q"]
    sag = z["sag"]
    est_log = z["est"]
    ref = z["ref"]
    upd = np.r_[False, np.any(np.abs(np.diff(sag, axis=0)) > 0, axis=1) & np.all(np.isfinite(sag[1:]), axis=1)]
    stops = pauses_from_ref(t, ref)
    droop = None
    if a.off:
        zo = np.load(a.off, allow_pickle=True)
        if stops:
            k1 = min(int(np.searchsorted(t, t[stops[0]] + 1.0)), len(t) - 1)
            droop = float(np.linalg.norm(zo["err_m"][k1])) * 1e3
    lines = ["# Teleop run: replay of the estimate with the speed weight (generated by experiments/stage2_teleop_offset_analysis.py teleop-replay)", "",
             "The replay re-runs the layer's low-pass (T = 2 s) on the logged sag, updating only on the ticks where the layer was called (the logged sag "
             "changes). Its w = 1 reproduces the logged estimate (check below). Approximation: the hand error at the pause is the droop (the correction-off "
             "error 1 s after the same stop) minus the replayed estimate's hand move, not a closed-loop result.", ""]
    dt = NOMINAL
    r1 = np.zeros((len(t), 7))
    e = np.zeros(7)
    for k in range(len(t)):
        if upd[k]:
            e = e + (dt / T_LOW) * (sag[k] - e)
        r1[k] = e
    lines.append(f"Check: replay with weight 1 against the logged estimate, largest difference {float(np.max(np.abs(r1 - est_log))):.2e} rad.")
    lines.append("")
    _setup()
    if not stops:
        lines.append("No stop.")
    else:
        ks = stops[0]
        lines += ["| s0 (rad/s) | estimate at the stop, hand space (mm) | at-rest droop (mm, correction off) | approx. hand error 1 s after the stop (mm) |",
                  "|---|---|---|---|"]
        for s0 in (None,) + S0:
            w_speed = np.zeros_like(q)
            w_speed[1:] = (q[1:] - q[:-1]) / dt
            w = np.ones_like(q) if s0 is None else 1.0 / (1.0 + (w_speed / s0) ** 2)
            e = np.zeros(7)
            for k in range(len(t)):
                if upd[k]:
                    e = e + (dt / T_LOW) * w[k] * (sag[k] - e)
                if k == ks:
                    break
            _, J = pad_and_jac(q[ks])
            eh = float(np.linalg.norm(J[:3] @ e)) * 1e3
            k1 = min(int(np.searchsorted(t, t[ks] + 1.0)), len(t) - 1)
            _, J1 = pad_and_jac(q[k1])
            # the approximation: the hand error after the stop is the droop minus the estimate's hand move (scalar)
            appr = float("nan") if droop is None else abs(droop - float(np.linalg.norm(J1[:3] @ e)) * 1e3)
            lines.append(f"| {'current (1)' if s0 is None else s0} | {eh:.2f} | {'' if droop is None else f'{droop:.2f}'} | {appr:.2f} |")
        lines.append("")
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print(f"teleop replay: wrote {out}")


