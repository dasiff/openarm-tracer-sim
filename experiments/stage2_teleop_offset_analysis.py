def pauses_from_ref(t, ref):
    """Stops: the reference unchanged for at least 1 s (finite samples only). Returns indices of the stop."""
    finite = np.all(np.isfinite(ref), axis=1)
    changed = np.r_[True, np.any(np.abs(np.diff(ref, axis=0)) > 0, axis=1)] | ~finite
    out = []
    i = 1
    while i < len(t):
        if changed[i - 1] and not changed[i]:
            j = i
            while j < len(t) and not changed[j]:
                j += 1
            if t[min(j, len(t) - 1)] - t[i] >= 1.0 and finite[i]:
                out.append(i)
            i = j
        else:
            i += 1
    return out


def cmd_teleop(a):
    z = np.load(a.run, allow_pickle=True)
    zo = np.load(a.off, allow_pickle=True) if a.off else None
    t = z["t"]
    q = z["q"]
    ref = z["ref"]
    pred = z["pred"]
    est = z["est"]
    sag = z["sag"]
    applied = z["applied"]
    clamp = z["clamp_updates"]
    dq = z["dq"]
    err = z["err_m"]
    bl = json.loads(str(z["bridge_log"])) if "bridge_log" in z.files else []
    lines = ["# Teleop: the offset after motion stops (generated by experiments/stage2_teleop_offset_analysis.py teleop)", "",
             f"Run: {a.run} ({len(t)} ticks, {t[0]:.2f} s to {t[-1]:.2f} s). Correction on. The input is a SCRIPTED operator, not recorded human data: "
             "src/teleop_source.py _FakeSource (in view 4 s of every 8 s) and _FakeSession (goal = 0.4 sin(t + joint index) on every joint, clipped "
             "to the joint limits; the applied target moves toward it at most TELEOP_MAX_JOINT_VEL per tick). The pause is the out-of-view half of the "
             "cycle: the arms hold their last pose.", ""]
    stops = pauses_from_ref(t, ref)
    lines.append(f"Stops (reference unchanged for at least 1 s, with a reference): {len(stops)}.")
    lines.append("")
    _setup()
    for k in stops:
        t_s = float(t[k])
        k1 = min(int(np.searchsorted(t, t_s + 1.0)), len(t) - 1)
        p1, J1 = pad_and_jac(q[k1])
        d_ref = ref[k1] - q[k1]
        contrib = np.array([J1[:3, j] * d_ref[j] for j in range(7)])          # per joint hand move of the reference error (m)
        total_lin = contrib.sum(axis=0)
        e_meas = float(np.linalg.norm(err[k1])) * 1e3 if np.all(np.isfinite(err[k1])) else float("nan")
        lines += [f"## Stop at {t_s:.2f} s; hand error 1 s after it: {e_meas:.2f} mm (logged)", "",
                  f"Linearised check: sum of the per-joint hand moves of (reference - measured) = {1e3 * np.linalg.norm(total_lin):.2f} mm.", "",
                  "| joint | reference - measured (deg) | per-joint hand move of that error (mm) | estimate (deg) | per-joint hand move of the estimate (mm) | "
                  "prediction error, predicted - measured (deg) | speed before the stop (rad/s) | acceleration around the stop (rad/s^2) |",
                  "|---|---|---|---|---|---|---|---|"]
        k_back = max(k - 30, 0)                                               # 0.2 s before the stop
        vel = (q[k] - q[k_back]) / max((t[k] - t[k_back]), 1e-9)
        vel_prev = (q[k_back] - q[max(k_back - 30, 0)]) / max((t[k_back] - t[max(k_back - 30, 0)]), 1e-9)
        acc = (vel - vel_prev) / max(t[k] - t[k_back], 1e-9)
        for j in range(7):
            hj = float(np.linalg.norm(J1[:3, j] * est[k1][j])) * 1e3
            lines.append(f"| {j + 1} | {np.degrees(d_ref[j]):+.3f} | {1e3 * np.linalg.norm(contrib[j]):.2f} | {np.degrees(est[k1][j]):+.3f} | {hj:.2f} | "
                         f"{np.degrees(pred[k1][j] - q[k1][j]):+.3f} | {vel[j]:+.3f} | {acc[j]:+.2f} |")
        lines.append("")
    if stops:
        k = stops[0]
        lines += ["## Build-up of the estimate, the offset and the hand move around the first stop", "",
                  "| time (s) | estimate norm (mrad) | offset |C_p| (mm) | estimate in hand space (mm) | prediction error norm (deg) | joint speed norm (rad/s) |",
                  "|---|---|---|---|---|---|---|"]
        for dt_s in np.arange(-3.0, 3.01, 0.5):
            kk = int(np.searchsorted(t, t[k] + dt_s))
            if kk >= len(t):
                break
            p_, J_ = pad_and_jac(q[kk])
            sp = float(np.linalg.norm((q[kk] - q[max(kk - 10, 0)]) / max(t[kk] - t[max(kk - 10, 0)], 1e-9)))
            lines.append(f"| {t[kk]:.2f} | {1e3 * np.linalg.norm(est[kk]):.2f} | {1e3 * np.linalg.norm(z['C_p'][kk]):.2f} | "
                         f"{1e3 * np.linalg.norm(J_[:3] @ est[kk]):.2f} | {np.degrees(np.linalg.norm(pred[kk] - q[kk])):.3f} | {sp:.3f} |")
        lines.append("")
    # bridge events
    kinds = {}
    for e in bl:
        kinds[e["kind"]] = kinds.get(e["kind"], 0) + int(e.get("count", 1))
    lines += ["## Bridge events (whole run)", "", f"Event counts: {kinds if kinds else 'none'}.", ""]
    if clamp.size:
        inc = clamp[-1] - clamp[0]
        lines.append("Buffer clamp updates per joint over the run (left arm): " + str([int(x) for x in inc]) +
                     "; the first clamp at " + str([round(float(t[np.argmax(clamp[:, j] > clamp[0, j])]), 2) if np.any(clamp[:, j] > clamp[0, j]) else None for j in range(7)]) + " s.")
        lines.append("")
    if zo is not None:
        eo = np.linalg.norm(zo["err_m"], axis=1) * 1e3
        lines.append(f"Correction off, same script: the hand error 1 s after the same stop is about {np.nanmean(eo[stops[0]:stops[0] + 60]) if stops else float('nan'):.2f} mm (mean over the 0.4 s after it).")
        lines.append("")
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print(f"teleop analysis: wrote {out}")


def _stop_indices(sched):
    return [float(s["t"]) for s in sched["stops"]]


