"""Per-joint breakdown of the five static holds, all rules (SF-125 decision 3). Analysis only: reads the static_<rule>.md files written by
experiments/climb_static.py and loads no simulator.

    python experiments/static_breakdown_table.py --root data/logs/stage2m --out data/logs/stage2n/static_breakdown.md

Per pose and joint, at the end of each hold (correction on): the droop at rest (correction off, from part (a)), the measured sag, the estimate,
the applied dq, the friction band (frictionloss/kp), whether the target is on the buffer clamp, and the hand contribution of the joint's
RESIDUAL droop (target minus settled, correction on), of its sag and of its dq, in mm (|J_joint * value| at the end of the hold).

Note on the md column labelled "hand contribution: droop (mm)": climb_static.py computes it from the correction-on end state, so it is the
residual miss after correction, not the at-rest droop of part (a). This script reports it under the name "residual".
"""

import argparse
import re
from pathlib import Path

RULES = [("integ", "production (integrator)"), ("meas_T0.25", "measure, T=0.25 s"), ("meas_T0.5", "measure, T=0.5 s"),
         ("meas_T1", "measure, T=1 s"), ("meas_T2", "measure, T=2 s")]
HEAD = re.compile(r"^### per joint at the end of the hold: (.+) \(left arm\)$")


def parse(md_path):
    """{pose: [ {joint, droop_a, sag, est, dq, band, clamp, resid_mm, sag_mm, dq_mm}, ... ]} from one static_<rule>.md."""
    out = {}
    pose = None
    for line in md_path.read_text().splitlines():
        m = HEAD.match(line)
        if m:
            pose = m.group(1)
            out[pose] = []
            continue
        if pose is None or not line.startswith("| ") or not re.match(r"^\| \d ", line):
            continue
        c = [x.strip() for x in line.strip("|").split("|")]
        out[pose].append({"joint": int(c[0]), "droop_a": float(c[1]), "sag": float(c[2]), "est": float(c[3]), "dq": float(c[4]),
                          "band": float(c[5]), "clamp": c[6], "resid_mm": float(c[7]), "sag_mm": float(c[8]), "dq_mm": float(c[9])})
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    root = Path(a.root)
    data = {}
    for tag, label in RULES:
        md = root / f"static_{tag}.md"
        if md.exists():
            data[label] = parse(md)
    lines = ["# Static holds: per-joint breakdown at the end of each hold, all rules (SF-125 decision 3; generated by experiments/static_breakdown_table.py)",
             "", "Units: mrad for angles, mm for the hand contributions (|J joint * value| at the end of the hold). "
                 "\"residual\" = the joint's target minus its settled position with correction on (the miss); "
                 "\"droop (a)\" = the same at rest with correction off.", ""]
    poses = list(next(iter(data.values())).keys()) if data else []
    # one table per rule: rows = pose x joint
    for label, per_pose in data.items():
        lines += [f"## {label}", "", "| pose | joint | droop (a) | measured sag | estimate | dq applied | friction band | on buffer clamp (fixed / range) | "
                  "residual hand (mm) | sag hand (mm) | dq hand (mm) |", "|---|---|---|---|---|---|---|---|---|---|---|"]
        for pose in poses:
            for r in per_pose.get(pose, []):
                lines.append(f"| {pose} | {r['joint']} | {r['droop_a']:+.2f} | {r['sag']:+.2f} | {r['est']:+.2f} | {r['dq']:+.2f} | "
                             f"{r['band']:.2f} | {r['clamp']} | {r['resid_mm']:.2f} | {r['sag_mm']:.2f} | {r['dq_mm']:.2f} |")
        lines.append("")
    # cross-rule summary: residual hand mm per joint, per pose and rule
    lines += ["## Residual hand miss per joint (mm), correction on, end of each hold: rows = pose and rule", "",
              "| pose | rule | j1 | j2 | j3 | j4 | j5 | j6 | j7 | largest |", "|---|---|---|---|---|---|---|---|---|---|"]
    for pose in poses:
        for label, per_pose in data.items():
            rows = per_pose.get(pose, [])
            if not rows:
                continue
            res = [r["resid_mm"] for r in rows]
            lines.append(f"| {pose} | {label} | " + " | ".join(f"{x:.2f}" for x in res) + f" | {max(res):.2f} (j{res.index(max(res)) + 1}) |")
    lines.append("")
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text("\n".join(lines) + "\n")
    print(f"static_breakdown_table: wrote {a.out}")


if __name__ == "__main__":
    main()
