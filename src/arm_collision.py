"""Collision filter for one arm's joint vectors (design plan §3.1): does this arm configuration hit the robot's own parts?

Code generated by Claude

The filter holds a private copy of the compiled model in which only the geoms that can touch the arm under test are switched on: the arm's own links (so its non-adjacent links
cannot hit each other), the other arm (held still at a given pose, by default the home pose), the torso, the three pedestal sections (the pedestal at its lowest, the worst case, by
default), the base with the battery pack, and the eagle camera's box (fixed to the torso; M153, M160). Furniture and objects are not part of it (the stance finder handles those, B2.9). A contact counts when it
involves a moving link of the arm under test (link1 to the hand and fingers; link0 is fixed to the torso), the other geom is one of the switched-on ones, and its distance is under
`margin` (negative is penetration). The model's own contact exclusions (adjacent links, the arm mounts on the torso, the pedestal stack) stay in force.

Contents:
    ArmCollisionChecker: build once per arm, then check(Q) for many joint vectors.
"""

import copy
import math

import mujoco
import numpy as np

from src import robot_specs
from src.robot_helpers import arm_ids


def bench_geoms(model, prefix="bench_"):
    """The collidable geoms of the bench in the loaded scene: the top, the legs and, when the bench is solid (TASK_CFG["bench_open"] False), the rails. They are found by name in the compiled model,
    so the open bench (rails removed by the scene hook) gives the top and the legs only; the sink, the faucet and the gas fittings that share the bench's body are not part of it.

    Args:
        model (mujoco.MjModel): The compiled scene.
        prefix (str): The geom names' start. Defaults to "bench_".

    Returns:
        list of int: Geom ids.
    """
    return [g for g in range(model.ngeom) if (model.geom(g).name or "").startswith(prefix) and (model.geom_contype[g] or model.geom_conaffinity[g])]


class ArmCollisionChecker:
    """Checks joint vectors of one arm for collisions with the robot's own parts.

    Attributes:
        model (mujoco.MjModel): The private model copy with the filter's geom selection.
        data (mujoco.MjData): Its data; the static parts are placed once, only the arm under test is moved.
        moving (numpy.ndarray): Bool per geom: belongs to a moving link of the arm under test.
        active (numpy.ndarray): Bool per geom: switched on.
        margin (float): Contacts closer than this count, metres.
    """

    def __init__(self, model, side, other_q, finger_open=None, pedestal_q=None, margin=0.0, bench=None):
        """Builds the filter.

        Args:
            model (mujoco.MjModel): The compiled robot model (with the camera body and the battery if the robot has them). It is copied, not changed.
            side (str): The arm under test, "left" or "right".
            other_q (array-like): The other arm's 7 joint angles while it is held still (radians), for example the home pose.
            finger_open (float or None): Opening of all four fingers, metres. Defaults to None, fully open (the finger joints' upper limit in the model).
            pedestal_q (float or None): The pedestal stage command (both stages, metres). Defaults to None, the lowest command (robot_specs.PEDESTAL_SPECS).
            margin (float): Contacts closer than this count as collisions, metres. Defaults to 0.0 (penetration only).
            bench (dict or None): Put the bench in the filter (David, 2026-10-23, C1; decisions-log M171): {"geoms": geom ids (bench_geoms(model)), "base_pose": (x, y, yaw) of the robot in the world,
                "pedestal_q": the pedestal command of that stance}. The robot is put at that pose, the pedestal stays at `pedestal_q` of the filter (the lowest by default: the worst case of the
                self-collisions) and the bench geoms are lowered by the stance's pedestal command, which gives the arm the same relative bench as at the stance. Defaults to None (no bench).
        """
        self.model = m = copy.copy(model)
        self.side = side
        self.margin = float(margin)
        other = "right" if side == "left" else "left"
        body_name = lambda g: m.body(int(m.geom_bodyid[g])).name
        col = np.array([bool(m.geom_contype[g] or m.geom_conaffinity[g]) for g in range(m.ngeom)])
        names = [body_name(g) for g in range(m.ngeom)]
        is_moving = lambda n: n.startswith(f"openarm_{side}_") and not n.endswith("link0")
        is_static = lambda n: (n.startswith(f"openarm_{other}_") and not n.endswith("link0")) or n == "openarm_body_link0" or n == "eagle_cam_body" or n.startswith("pedestal_") \
            or n == "battery" or n == "base_link"
        self.moving = np.array([col[g] and is_moving(names[g]) for g in range(m.ngeom)])
        static = np.array([col[g] and is_static(names[g]) for g in range(m.ngeom)])
        if bench is not None:
            for g in bench["geoms"]:
                static[g] = True
                m.geom_pos[g, 2] -= float(bench["pedestal_q"])             # the bench's body is at the world origin: the geom position is the world position
        self.active = self.moving | static
        for g in range(m.ngeom):                         # switch everything else off (the beaker's explicit contact pairs are ignored by the filter below)
            if not self.active[g]:
                m.geom_contype[g] = 0
                m.geom_conaffinity[g] = 0
        m.geom_margin[self.active] = max(self.margin, 0.0)
        self.data = d = mujoco.MjData(m)
        bx, by, byaw = (0.0, 0.0, 0.0) if bench is None else bench["base_pose"]
        d.qpos[0:7] = [bx, by, 0.1527, math.cos(byaw / 2), 0.0, 0.0, math.sin(byaw / 2)]
        pq = robot_specs.PEDESTAL_SPECS["lowest_command"] if pedestal_q is None else pedestal_q
        for jn in robot_specs.PEDESTAL_SPECS["joints"]:
            d.qpos[m.joint(jn).qposadr[0]] = pq
        for a, v in zip(arm_ids(m, other)["qadr"], other_q):
            d.qpos[a] = v
        for sd in ("left", "right"):
            for j in arm_ids(m, sd)["finger_jnt"]:
                d.qpos[m.jnt_qposadr[j]] = m.jnt_range[j, 1] if finger_open is None else finger_open
        self.qadr = arm_ids(m, side)["qadr"]
        mujoco.mj_kinematics(m, d)

    def check(self, Q):
        """Tells which joint vectors of the arm under test collide.

        Args:
            Q (numpy.ndarray): Joint angles (N, 7), radians.

        Returns:
            numpy.ndarray: Bool (N,): True where a moving link of the arm touches (or is within `margin` of) the other arm, itself, the torso, the pedestal, the base, the battery or the eagle camera's box.
        """
        m, d, act, mov = self.model, self.data, self.active, self.moving
        Q = np.atleast_2d(Q)
        out = np.zeros(len(Q), bool)
        for n, q in enumerate(Q):
            d.qpos[self.qadr] = q
            mujoco.mj_kinematics(m, d)
            mujoco.mj_collision(m, d)
            nc = d.ncon
            if nc:
                g1, g2 = d.contact.geom1[:nc], d.contact.geom2[:nc]
                hit = act[g1] & act[g2] & (mov[g1] | mov[g2]) & (d.contact.dist[:nc] < self.margin)
                out[n] = bool(hit.any())
        return out
