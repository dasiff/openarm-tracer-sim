"""Batch forward kinematics, the analytic Jacobian and a bounded damped-least-squares inverse kinematics solver for one OpenArm arm.

Code generated by Claude

Moved here from the superseded experiments/beaker_hotplate_staging_search.py (which now imports it). Pure numpy: the arm's chain of static transforms and hinge axes is read
from the compiled MuJoCo model once (arm_chain), after that nothing needs MuJoCo. Many joint vectors are handled at once. All poses are in the torso frame (the openarm_body_link0
frame: x forward, y left, z up, upright whatever the pedestal height; the pedestal and the base only move that frame rigidly). A point on the hand is given as an offset in the
tool point frame (the hand_tcp body). Which axes of that frame are the approach and the finger-closing directions is not assumed here: src/gripper_geometry.py derives them from the model.

Contents:
    arm_chain(model, side): the chain of one arm.
    shoulder_origin(chain): the arm's shoulder mount (the origin of its link0 frame) in the torso frame.
    batch_fk(chain, Q, offset): positions and rotations of the tool point (or a point offset from it) for many joint vectors.
    batch_fk_jac(chain, Q, offset): the same with the position and angular Jacobians.
    solve_ik(chain, Q0, lo, hi, constraint, offset, ...): damped least squares from many start vectors, with a constraint callback.
    position_constraint(target, tol): the constraint "the point is at the target".
"""

import mujoco
import numpy as np

LINKS = ("link0", "link1", "link2", "link3", "link4", "link5", "link6", "link7", "link8", "hand", "hand_tcp")


def _quat2mat(q):
    """Rotation matrix of a quaternion (w, x, y, z).

    Args:
        q (array-like): The quaternion.

    Returns:
        numpy.ndarray: The 3 x 3 rotation matrix.
    """
    R = np.zeros(9)
    mujoco.mju_quat2Mat(R, np.asarray(q, float))
    return R.reshape(3, 3)


def arm_chain(model, side):
    """Reads the static transforms and hinge axes from the torso down to the tool point of one arm.

    Args:
        model (mujoco.MjModel): The compiled model.
        side (str): "left" or "right".

    Returns:
        list of tuple: One entry per body from link0 to hand_tcp: (position in the parent frame (3,), rotation relative to the parent (3, 3), hinge axis in the body frame (3,)
        or None for a body without a joint). The seven hinge axes are in joint order.
    """
    out = []
    for n in LINKS:
        b = model.body(f"openarm_{side}_{n}")
        axis = None
        if b.jntnum[0] > 0:
            jid = int(b.jntadr[0])
            assert model.jnt_type[jid] == mujoco.mjtJoint.mjJNT_HINGE and np.allclose(model.jnt_pos[jid], 0)
            axis = model.jnt_axis[jid].copy()
        out.append((model.body_pos[b.id].copy(), _quat2mat(model.body_quat[b.id]), axis))
    return out


def shoulder_origin(chain):
    """Gives the arm's shoulder mount: the origin of its link0 frame in the torso frame.

    Args:
        chain (list): From arm_chain.

    Returns:
        numpy.ndarray: The shoulder position (3,), metres.
    """
    return chain[0][0].copy()


def _rodrigues(ax, q):
    """Rotation matrices about the axis `ax` by the angles `q` (N,)."""
    K = np.array([[0, -ax[2], ax[1]], [ax[2], 0, -ax[0]], [-ax[1], ax[0], 0]])
    c, s = np.cos(q)[:, None, None], np.sin(q)[:, None, None]
    return c * np.eye(3) + s * K + (1 - c) * np.outer(ax, ax)


def batch_fk(chain, Q, offset=None):
    """Forward kinematics of many joint vectors.

    Args:
        chain (list): From arm_chain.
        Q (numpy.ndarray): Joint angles (N, 7), radians.
        offset (array-like or None): A point in the tool point frame, metres (for example the pad centre). Defaults to None, the tool point itself.

    Returns:
        tuple: (positions (N, 3) of the point, rotations (N, 3, 3) of the tool point frame), in the torso frame.
    """
    p, R, _, _ = _fk(chain, Q, offset, jac=False)
    return p, R


def batch_fk_jac(chain, Q, offset=None):
    """Forward kinematics with the Jacobians.

    Args:
        chain (list): From arm_chain.
        Q (numpy.ndarray): Joint angles (N, 7), radians.
        offset (array-like or None): A point in the tool point frame, metres. Defaults to None, the tool point.

    Returns:
        tuple: (positions (N, 3), rotations (N, 3, 3), Jv (N, 3, 7), Jw (N, 3, 7)): Jv is the derivative of the point's position and Jw the angular velocity (the hinge axis in
        the world) per unit of each joint, so that dp = Jv dq and, for a vector v fixed to the hand, dv = (Jw dq) x v.
    """
    return _fk(chain, Q, offset, jac=True)


def _fk(chain, Q, offset, jac):
    N = len(Q)
    R = np.tile(np.eye(3), (N, 1, 1))
    p = np.zeros((N, 3))
    axes, origins = [], []
    k = 0
    for pos, Rs, ax in chain:
        p = p + R @ pos
        R = R @ Rs
        if ax is not None:
            if jac:
                axes.append(R @ ax)
                origins.append(p.copy())
            R = R @ _rodrigues(ax, Q[:, k])
            k += 1
    if offset is not None:
        p = p + R @ np.asarray(offset, float)
    if not jac:
        return p, R, None, None
    W = np.stack(axes, axis=2)                                   # (N, 3, 7)
    O = np.stack(origins, axis=2)                                # (N, 3, 7)
    Jv = np.cross(W, p[:, :, None] - O, axis=1)
    return p, R, Jv, W


def position_constraint(target, tol=5e-4):
    """Makes the constraint callback "the point is at the target position".

    Args:
        target (numpy.ndarray): The target (3,) or one per start vector (N, 3), torso frame, metres.
        tol (float): The position error that counts as reached, metres. Defaults to 5e-4.

    Returns:
        callable: constraint(p, R, Jv, Jw, idx) -> (r (n, 3), J (n, 3, 7), ok (n,)) as solve_ik expects; idx are the rows (of the start vectors) being evaluated.
    """
    target = np.asarray(target, float)

    def constraint(p, R, Jv, Jw, idx):
        t = target if target.ndim == 1 else target[idx]
        r = p - t
        return r, Jv, np.linalg.norm(r, axis=1) < tol

    return constraint


def solve_ik(chain, Q0, lo, hi, constraint, offset=None, max_iter=40, damping=0.02, max_step=0.3):
    """Solves many inverse kinematics problems at once with bounded damped least squares.

    Each iteration takes the step dq = -J^T (J J^T + damping^2 I)^-1 r (J the Jacobian of the constraint's residual r), at most max_step rad on any joint, and clips the joints to
    [lo, hi]. A start vector stops as soon as the constraint says it is satisfied.

    Args:
        chain (list): From arm_chain.
        Q0 (numpy.ndarray): Start joint vectors (N, 7), radians (clipped to the bounds first).
        lo (numpy.ndarray): Lower joint bounds (7,), radians.
        hi (numpy.ndarray): Upper joint bounds (7,), radians.
        constraint (callable): constraint(p, R, Jv, Jw, idx) -> (r (n, k), J (n, k, 7), ok (n,)): the residual that should become zero (rows that are inside a tolerance band
            are zero and have a zero Jacobian row), its Jacobian with respect to the joints, and whether each is satisfied (to its full tolerance). p, R, Jv and Jw
            are from batch_fk_jac for the rows `idx` still being worked on.
        offset (array-like or None): The point on the hand, as in batch_fk. Defaults to None.
        max_iter (int): Iteration limit. Defaults to 40.
        damping (float): The damping of the least squares. Defaults to 0.02.
        max_step (float): Largest joint change per iteration, radians. Defaults to 0.3.

    Returns:
        tuple: (joint vectors (N, 7), satisfied (N,) bool, iterations used (N,) int).
    """
    Q = np.clip(np.asarray(Q0, float), lo, hi)
    N = len(Q)
    done = np.zeros(N, bool)
    iters = np.zeros(N, int)
    active = np.arange(N)
    for it in range(max_iter + 1):
        if len(active) == 0:
            break
        p, R, Jv, Jw = batch_fk_jac(chain, Q[active], offset)
        r, J, ok = constraint(p, R, Jv, Jw, active)
        done[active[ok]] = True
        iters[active] = it
        keep = ~ok
        active = active[keep]
        if it == max_iter or len(active) == 0:
            break
        r, J = r[keep], J[keep]
        k = J.shape[1]
        y = np.linalg.solve(J @ J.transpose(0, 2, 1) + damping ** 2 * np.eye(k), r[..., None])
        dq = -(J.transpose(0, 2, 1) @ y)[..., 0]
        n = np.abs(dq).max(axis=1, keepdims=True)
        dq = dq * np.minimum(1.0, max_step / np.maximum(n, 1e-12))
        Q[active] = np.clip(Q[active] + dq, lo, hi)
    return Q, done, iters
