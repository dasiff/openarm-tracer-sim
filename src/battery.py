"""The battery pack (Anker SOLIX C800) as a box on the robot, added to the model at load time.

Code generated by Claude

PLACEHOLDER: the real mount is unconfirmed (see robot_specs.BATTERY_SPECS). Same pattern as src/pedestal.py: the XML stays untouched and RobotSimulator
applies this through MjSpec before compiling.
"""

import mujoco


def add_battery(spec, battery_specs):
    """Adds the battery pack as a box on its own body, welded to the mount body.

    The box has the specification's mass spread uniformly (MuJoCo computes the inertia from the box) and collides like any other geom. It needs a body of its own:
    base_link has an explicit inertial element, so a mass given to a geom on base_link would be ignored.

    Args:
        spec (mujoco.MjSpec): The model specification, before compiling.
        battery_specs (dict): robot_specs.BATTERY_SPECS.

    Raises:
        ValueError: If the mount body is not in the model.
    """
    mount = spec.body(battery_specs["mount_body"])
    if mount is None:
        raise ValueError(f"battery: mount body '{battery_specs['mount_body']}' not found in model")
    body = mount.add_body()
    body.name = battery_specs["name"]
    body.pos = list(battery_specs["pos"])
    body.quat = list(battery_specs["quat"])
    geom = body.add_geom()
    geom.name = f"{battery_specs['name']}_geom"
    geom.type = mujoco.mjtGeom.mjGEOM_BOX
    geom.size = [0.5 * v for v in battery_specs["size"]]
    geom.mass = battery_specs["mass"]
    geom.rgba = list(battery_specs["rgba"])
