"""The layered furniture map (design plan §3.4): where the robot cannot stand, from the scene's collision geometry, in two height layers.

Code generated by Claude

Every collidable geom that is not part of the robot is projected onto the floor and rasterized into one or both of two occupancy layers, according to the height band its vertical extent
overlaps: the "base" layer (what the chassis and the battery can hit) and the "arm" layer (what the torso, the pedestal and the arms can hit above that: a table top that the base can drive
under is in the arm layer only). `blocked(heading, footprint)` then gives the robot origin positions that are not allowed at a heading: the base layer grown by the robot's footprint
rotated to the heading (a position is blocked if the chassis there would overlap an obstacle), the arm layer grown by a disc of radius FURNITURE_CFG["arm_layer_radius"] (a first
approximation of the torso and arm sweep; the real arm-to-furniture check is the verification step, B2.12), and everything outside the grid.

All floor grids are indexed [iy, ix] (rows are y, columns are x: the image convention, so that OpenCV can draw and grow them); cell (iy, ix) covers x from x0 + ix * res to x0 + (ix + 1) * res.

Contents:
    FurnitureMap: the layers and the queries.
    geom_points_world(model, data, g): sample points of a geom's surface in the world (the basis of the rasterization).
    footprint_polygon(model, data, bodies): the convex footprint of the robot's base in its own frame.
"""

import cv2
import mujoco
import numpy as np
from scipy.spatial import ConvexHull

from src.task_config import FURNITURE_CFG

_UNIT_RING = np.array([[np.cos(t), np.sin(t)] for t in np.linspace(0, 2 * np.pi, 33)[:-1]])


def geom_points_world(model, data, g):
    """Samples points on a geom (its vertices, corners, rims or surface), in the world frame.

    Args:
        model (mujoco.MjModel): The compiled model.
        data (mujoco.MjData): Its data, after a forward kinematics pass.
        g (int): The geom id.

    Returns:
        numpy.ndarray or None: Points (N, 3), metres, or None for a geom that cannot block anything (a plane or a height field).

    Raises:
        NotImplementedError: For a geom type that is not handled (sdf).
    """
    t = int(model.geom_type[g])
    s = model.geom_size[g]
    R, p = data.geom_xmat[g].reshape(3, 3), data.geom_xpos[g]
    T = mujoco.mjtGeom
    if t in (T.mjGEOM_PLANE, T.mjGEOM_HFIELD):
        return None
    if t == T.mjGEOM_BOX:
        L = np.array([[sx * s[0], sy * s[1], sz * s[2]] for sx in (-1, 1) for sy in (-1, 1) for sz in (-1, 1)])
    elif t == T.mjGEOM_MESH:
        mid = model.geom_dataid[g]
        L = model.mesh_vert[model.mesh_vertadr[mid]:model.mesh_vertadr[mid] + model.mesh_vertnum[mid]].astype(float)
    elif t == T.mjGEOM_CYLINDER:
        L = np.concatenate([np.c_[s[0] * _UNIT_RING, np.full(len(_UNIT_RING), z)] for z in (-s[1], s[1])])
    elif t == T.mjGEOM_CAPSULE:
        sph = [np.c_[s[0] * np.cos(a) * _UNIT_RING, np.full(len(_UNIT_RING), s[0] * np.sin(a) + dz)] for dz in (-s[1], s[1]) for a in np.linspace(-np.pi / 2, np.pi / 2, 9)]
        L = np.concatenate(sph)
    elif t in (T.mjGEOM_SPHERE, T.mjGEOM_ELLIPSOID):
        ax = s if t == T.mjGEOM_ELLIPSOID else np.full(3, s[0])
        L = np.concatenate([np.c_[ax[0] * np.cos(a) * _UNIT_RING, ax[2] * np.full(len(_UNIT_RING), np.sin(a))] * [1, 1, 1] for a in np.linspace(-np.pi / 2, np.pi / 2, 9)])
        L[:, 1] = L[:, 1] * ax[1] / ax[0]
    else:
        raise NotImplementedError(f"geom type {t}")
    return L @ R.T + p


def footprint_polygon(model, data, bodies):
    """Gives the convex footprint of some bodies' collision geoms in the base frame (seen from above).

    Args:
        model (mujoco.MjModel): The compiled model.
        data (mujoco.MjData): Its data, after a forward kinematics pass, with the base at any pose.
        bodies (iterable of int): The body ids whose collision geoms make up the footprint (the base and the battery).

    Returns:
        numpy.ndarray: The hull's corners (K, 2) in the base frame (x forward, y left) of the first body of `bodies`, metres.
    """
    bodies = list(bodies)
    root = bodies[0]
    pts = []
    for g in range(model.ngeom):
        if int(model.geom_bodyid[g]) in bodies and (model.geom_contype[g] or model.geom_conaffinity[g]):
            P = geom_points_world(model, data, g)
            if P is not None:
                pts.append(P)
    P = np.concatenate(pts)
    local = (P - data.xpos[root]) @ data.xmat[root].reshape(3, 3)
    hull = ConvexHull(local[:, :2])
    return local[hull.vertices, :2]


def _fill_convex(img, poly):
    """Sets the cells of `img` whose centre lies inside a convex polygon (so areas are not fattened by the cells on the boundary); a polygon smaller than a cell still sets the cell of its centroid.

    Args:
        img (numpy.ndarray): uint8 array (ny, nx), changed in place.
        poly (numpy.ndarray): The polygon's corners (K, 2) in cell-centre coordinates (x = column, y = row), counter-clockwise.
    """
    x0, y0 = np.floor(poly.min(axis=0)).astype(int) - 1
    x1, y1 = np.ceil(poly.max(axis=0)).astype(int) + 2
    x0, y0, x1, y1 = max(x0, 0), max(y0, 0), min(x1, img.shape[1]), min(y1, img.shape[0])
    if x1 <= x0 or y1 <= y0:
        return
    gx, gy = np.meshgrid(np.arange(x0, x1), np.arange(y0, y1))
    inside = np.ones(gx.shape, bool)
    for a, b in zip(poly, np.roll(poly, -1, axis=0)):
        inside &= (b[0] - a[0]) * (gy - a[1]) - (b[1] - a[1]) * (gx - a[0]) >= -1e-9
    img[y0:y1, x0:x1][inside] = 1
    cx, cy = int(round(poly[:, 0].mean())), int(round(poly[:, 1].mean()))
    if 0 <= cx < img.shape[1] and 0 <= cy < img.shape[0]:
        img[cy, cx] = 1


class FurnitureMap:
    """Two occupancy layers of the floor and the blocked-position queries.

    Attributes:
        res (float): Cell edge, metres.
        origin (numpy.ndarray): (x0, y0), the lower corner of the grid, metres.
        shape (tuple of int): (rows, columns) = (ny, nx).
        layers (dict): "base" and "arm": bool arrays of that shape, True where an obstacle is.
        arm_radius (float): The radius of the disc the arm layer is grown by, metres.
    """

    def __init__(self, layers, origin, res, arm_radius):
        """Makes a map from ready layers (also used by the tests for synthetic maps).

        Args:
            layers (dict): "base" and "arm" bool arrays, shape (ny, nx), True = obstacle.
            origin (array-like): (x0, y0) of the grid's lower corner, metres.
            res (float): Cell edge, metres.
            arm_radius (float): The arm layer's growth radius, metres.
        """
        self.layers = {k: np.asarray(v, bool) for k, v in layers.items()}
        self.shape = self.layers["base"].shape
        self.origin = np.asarray(origin, float)
        self.res = float(res)
        self.arm_radius = float(arm_radius)
        self._cache = {}

    @classmethod
    def from_model(cls, model, data, cfg=FURNITURE_CFG, robot_root="base_link", exclude_bodies=()):
        """Rasterizes the scene's collidable geoms into the two layers.

        Args:
            model (mujoco.MjModel): The compiled model.
            data (mujoco.MjData): Its data (the geoms' world poses come from a forward kinematics pass done here).
            cfg (dict): FURNITURE_CFG. Defaults to it.
            robot_root (str): The robot's root body; its subtree is left out. Defaults to "base_link".
            exclude_bodies (iterable of str): Further bodies to leave out, for example the object that is the task's target. Defaults to none.

        Returns:
            FurnitureMap: The map.
        """
        mujoco.mj_kinematics(model, data)
        root = model.body(robot_root).id
        skip = {model.body(n).id for n in exclude_bodies}

        def under(b, top):
            while b > 0:
                if b == top:
                    return True
                b = int(model.body_parentid[b])
            return False

        x0, x1, y0, y1 = cfg["bounds"]
        res = cfg["resolution"]
        nx, ny = int(round((x1 - x0) / res)), int(round((y1 - y0) / res))
        layers = {"base": np.zeros((ny, nx), np.uint8), "arm": np.zeros((ny, nx), np.uint8)}
        bands = {"base": cfg["base_band"], "arm": cfg["arm_band"]}
        for g in range(model.ngeom):
            b = int(model.geom_bodyid[g])
            if not (model.geom_contype[g] or model.geom_conaffinity[g]) or under(b, root) or any(under(b, s) for s in skip):
                continue
            P = geom_points_world(model, data, g)
            if P is None:
                continue
            zlo, zhi = P[:, 2].min(), P[:, 2].max()
            hit = [k for k, (lo, hi) in bands.items() if zhi > lo and zlo < hi]
            if not hit:
                continue
            xy = P[:, :2]
            poly = xy[ConvexHull(xy).vertices] if len(xy) >= 3 else xy
            cells = (poly - [x0, y0]) / res - 0.5                                # cell centres at integer coordinates
            for k in hit:
                _fill_convex(layers[k], cells)
        return cls(layers, (x0, y0), res, cfg["arm_layer_radius"])

    def cell_of(self, xy):
        """Gives the cell indices of points.

        Args:
            xy (numpy.ndarray): Points (N, 2), metres.

        Returns:
            tuple: (iy (N,), ix (N,), inside (N,) bool: whether the cell lies in the grid).
        """
        c = np.floor((np.atleast_2d(xy) - self.origin) / self.res).astype(int)
        ix, iy = c[:, 0], c[:, 1]
        return iy, ix, (ix >= 0) & (ix < self.shape[1]) & (iy >= 0) & (iy < self.shape[0])

    def occupied(self, layer, xy):
        """Tells whether points are inside an obstacle of a layer (outside the grid counts as occupied).

        Args:
            layer (str): "base" or "arm".
            xy (numpy.ndarray): Points (N, 2), metres.

        Returns:
            numpy.ndarray: Bool (N,).
        """
        iy, ix, ok = self.cell_of(xy)
        out = np.ones(len(ix), bool)
        out[ok] = self.layers[layer][iy[ok], ix[ok]]
        return out

    def _grow(self, layer, kernel_poly):
        """The layer grown by a convex polygon (corners in metres, relative to the robot origin): cell p is set when the polygon placed at p touches an obstacle."""
        r = self.res
        k = int(np.ceil(np.abs(kernel_poly).max() / r)) + 2
        ker = np.zeros((2 * k + 1, 2 * k + 1), np.uint8)
        cv2.fillConvexPoly(ker, np.round(kernel_poly / r + k).astype(np.int32), 1)
        return cv2.dilate(self.layers[layer].astype(np.uint8), ker, anchor=(k, k), borderType=cv2.BORDER_CONSTANT, borderValue=0).astype(bool)

    def blocked(self, heading, footprint, arm_kernel=None):
        """Gives the robot origin positions that are not allowed at a heading.

        Args:
            heading (float): The robot's heading, radians (0 = facing +x, counter-clockwise).
            footprint (numpy.ndarray): The base footprint's corners (K, 2) in the base frame, metres (footprint_polygon).
            arm_kernel (numpy.ndarray or None): What the arm layer is grown by: a convex polygon (K, 2) in the base frame, metres, turned by the heading (for the torso and pedestal
                column's real cross-section, src/stance_finder.column_polygon_fn). Defaults to None, the disc of radius arm_radius (the first approximation).

        Returns:
            numpy.ndarray: Bool array of the grid's shape, True where the robot origin may not be: the base layer grown by the rotated footprint, the arm layer grown by the arm
            kernel, and (the grid's edge being where obstacles outside it begin) the cells whose footprint leaves the grid.
        """
        key = (round(float(heading), 6), footprint.tobytes(), None if arm_kernel is None else np.round(arm_kernel, 6).tobytes())
        if key not in self._cache:
            c, s = np.cos(heading), np.sin(heading)
            rot = np.array([[c, s], [-s, c]])
            poly = footprint @ rot                                                # rotated by the heading (rows are points: R @ f)
            bkey = ("base", round(float(heading), 6), footprint.tobytes())
            if bkey not in self._cache:
                self._cache[bkey] = self._grow("base", poly)
            base = self._cache[bkey]
            if arm_kernel is None:
                ang = np.linspace(0, 2 * np.pi, 48, endpoint=False)
                kpoly = self.arm_radius * np.c_[np.cos(ang), np.sin(ang)]
            else:
                kpoly = np.asarray(arm_kernel, float) @ rot
            arm = self._grow("arm", kpoly)
            blocked = base | arm
            # the footprint must lie inside the grid: block the cells whose rotated footprint crosses the edge (the walls are in the layers, this keeps a bad grid from leaking)
            ext = np.abs(poly).max(axis=0)
            nx_, ny_ = int(np.ceil(ext[0] / self.res)), int(np.ceil(ext[1] / self.res))
            blocked[:ny_, :] = True
            blocked[-ny_:, :] = True
            blocked[:, :nx_] = True
            blocked[:, -nx_:] = True
            self._cache[key] = blocked
        return self._cache[key]
