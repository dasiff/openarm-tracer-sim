"""The rules that make a hand pose a map grasp (design plan §3.1): level, a side grasp, an approach direction bin, and a margin from the joint limits.

Code generated by Claude

All numbers are in GRASP_MAP_CFG (src/task_config.py), completed for one arm by src/gripper_geometry.grasp_cfg (the approach axis, the finger-closing axis and the pad centre, which are
derived from the model, not assumed). A pose is a grasp when the approach axis and the finger-closing axis are both within
level_deg of horizontal (the fingers close sideways, so the pads stand vertical and a beaker held between them stays upright), and the approach direction falls in one of the
n_bins bins that tile the circle, bin k being centred at k * 360 / n_bins degrees from the robot's forward axis (+x of the torso frame) towards its left (+y) and accepting
+-bin_half_deg. The joints must also be at least joint_margin_deg from both limits (joint_bounds). The mapped point is the pad centre (pad_center_in_tcp).

Contents:
    azimuth(R): the approach direction's angle from the forward axis, radians.
    classify(R, cfg): which poses are level and in which bin they approach.
    rule_ok(R, k, cfg): whether poses are level and approach in bin k.
    bin_center(k, cfg): the centre of bin k, radians.
    joint_bounds(model, side, cfg): the joint limits shrunk by the margin.
    make_constraint(target, k, cfg): the IK constraint "the pad centre is at the target and the grasp rule holds" for src/arm_kinematics.solve_ik.
"""

import math

import numpy as np

from src.robot_helpers import arm_ids
from src.task_config import GRASP_MAP_CFG


def _axes(R, cfg):
    """The approach axis and the finger-closing axis in the torso frame: the tool frame rotations times the axes derived from the model."""
    return R @ np.asarray(cfg["approach_axis"], float), R @ np.asarray(cfg["closing_axis"], float)


def azimuth(R, cfg):
    """Gives the direction the hand approaches in, seen from above.

    Args:
        R (numpy.ndarray): Tool frame rotations (N, 3, 3) in the torso frame.
        cfg (dict): The settings completed by grasp_cfg (it holds the approach axis).

    Returns:
        numpy.ndarray: The angle of the approach axis's horizontal part from the forward axis towards the left, radians in (-pi, pi], shape (N,).
    """
    a = R @ np.asarray(cfg["approach_axis"], float)
    return np.arctan2(a[:, 1], a[:, 0])


def bin_center(k, cfg=GRASP_MAP_CFG):
    """Gives the centre direction of an approach bin.

    Args:
        k (int): The bin, 0 to n_bins - 1.
        cfg (dict): GRASP_MAP_CFG.

    Returns:
        float: The angle from the forward axis towards the left, radians.
    """
    return 2.0 * math.pi * k / cfg["n_bins"]


def _wrap(a):
    return (a + math.pi) % (2.0 * math.pi) - math.pi


def classify(R, cfg):
    """Tells which poses are level and which approach bin they fall in.

    Args:
        R (numpy.ndarray): Tool frame rotations (N, 3, 3) in the torso frame.
        cfg (dict): The settings completed by grasp_cfg.

    Returns:
        tuple: (level (N,) bool: approach axis and finger axis both within level_deg of horizontal, bin (N,) int: the bin of the approach direction, 0 to n_bins - 1, meaningful
        where level; the bins tile the circle, a direction exactly on a boundary goes to the higher bin).
    """
    s = math.sin(math.radians(cfg["level_deg"]))
    a, y = _axes(R, cfg)
    level = (np.abs(a[:, 2]) <= s) & (np.abs(y[:, 2]) <= s)
    width = 2.0 * math.pi / cfg["n_bins"]
    k = np.floor((np.arctan2(a[:, 1], a[:, 0]) + 0.5 * width) / width).astype(int) % cfg["n_bins"]
    return level, k


def rule_ok(R, k, cfg):
    """Tells which poses are level and approach in bin k.

    Args:
        R (numpy.ndarray): Tool frame rotations (N, 3, 3).
        k (int): The bin.
        cfg (dict): The settings completed by grasp_cfg.

    Returns:
        numpy.ndarray: Bool (N,).
    """
    s = math.sin(math.radians(cfg["level_deg"]))
    a, y = _axes(R, cfg)
    d = np.abs(_wrap(np.arctan2(a[:, 1], a[:, 0]) - bin_center(k, cfg)))
    return (np.abs(a[:, 2]) <= s) & (np.abs(y[:, 2]) <= s) & (d <= math.radians(cfg["bin_half_deg"]) + 1e-12)


def joint_bounds(model, side, cfg=GRASP_MAP_CFG):
    """Gives the joint limits of one arm shrunk by the margin.

    Args:
        model (mujoco.MjModel): The compiled model.
        side (str): "left" or "right".
        cfg (dict): GRASP_MAP_CFG.

    Returns:
        tuple: (lower (7,), upper (7,)) in radians.
    """
    rng = model.jnt_range[arm_ids(model, side)["jnt"]]
    m = math.radians(cfg["joint_margin_deg"])
    return rng[:, 0] + m, rng[:, 1] - m


def make_constraint(target, k, cfg):
    """Makes the IK constraint "the pad centre is at the target and the pose is a grasp in bin k".

    The position rows are the position error. The three rule rows (approach elevation, finger axis elevation, approach direction) are zero while the pose is inside cfg["ik_soft"]
    times the tolerance, and push back past it, so solutions end inside the tolerance. "Satisfied" is the full tolerance and cfg["ik_pos_tol"] for the position.

    Args:
        target (numpy.ndarray): The pad centre target (3,) or one per start vector (N, 3), in the torso frame, metres.
        k (int or None): The approach bin, or None for no direction constraint (only level).
        cfg (dict): The settings completed by grasp_cfg.

    Returns:
        callable: constraint(p, R, Jv, Jw, idx) -> (r (n, 6), J (n, 6, 7), ok (n,)) for src/arm_kinematics.solve_ik, used with offset = cfg["pad_center_in_tcp"].
    """
    target = np.asarray(target, float)
    lev = math.sin(math.radians(cfg["level_deg"]))
    half = math.radians(cfg["bin_half_deg"])
    soft = cfg["ik_soft"]
    centre = None if k is None else bin_center(k, cfg)

    def constraint(p, R, Jv, Jw, idx):
        t = target if target.ndim == 1 else target[idx]
        n = len(p)
        a, y = _axes(R, cfg)
        da = np.cross(Jw, a[:, :, None], axis=1)                  # d a / d q, (n, 3, 7): the approach axis turns with the joints
        dy = np.cross(Jw, y[:, :, None], axis=1)
        r = np.zeros((n, 6))
        J = np.zeros((n, 6, 7))
        r[:, :3] = p - t
        J[:, :3] = Jv
        for row, v, dv in ((3, a[:, 2], da[:, 2]), (4, y[:, 2], dy[:, 2])):
            ex = np.maximum(0.0, np.abs(v) - soft * lev)
            act = ex > 0
            r[:, row] = ex
            J[:, row] = np.where(act[:, None], np.sign(v)[:, None] * dv, 0.0)
        ok = (np.linalg.norm(p - t, axis=1) < cfg["ik_pos_tol"]) & (np.abs(a[:, 2]) <= lev) & (np.abs(y[:, 2]) <= lev)
        if centre is not None:
            phi = np.arctan2(a[:, 1], a[:, 0])
            dphi = _wrap(phi - centre)
            ex = np.maximum(0.0, np.abs(dphi) - soft * half)
            h2 = np.maximum(a[:, 0] ** 2 + a[:, 1] ** 2, 1e-12)
            dphi_dq = (a[:, 0:1] * da[:, 1] - a[:, 1:2] * da[:, 0]) / h2[:, None]
            r[:, 5] = ex
            J[:, 5] = np.where((ex > 0)[:, None], np.sign(dphi)[:, None] * dphi_dq, 0.0)
            ok &= np.abs(dphi) <= half
        return r, J, ok

    return constraint
