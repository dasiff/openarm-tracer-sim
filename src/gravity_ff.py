"""Gravity feedforward torque for the arm joints (decisions-log M185): the stand-in for the real controller's gravity compensation.

Code generated by Claude

The real motors run MIT mode: tau = kp (q* - q) + kd (qd* - qd) + tau_ff. Here tau_ff is gravity's pull on each arm joint at the measured pose, from the ARM'S OWN bodies only, and it is added
to the position actuator's target as ctrl = q_target + tau_ff / kp, which makes the actuator's force exactly kp (q_target - q) - kd qd + tau_ff (then limited to the motor's torque, as MIT mode
limits the sum). Gravity only: no Coriolis, no inertia term.

How a held object's weight stays out
  * The bodies that count are exactly the names in robot_specs.ARM_ACTUATOR_SPECS["gravcomp_bodies"] of each arm (link1 to link7, hand, hand_tcp, the two fingers): the robot's own links, whose
    masses are the arm description's (the model's body_mass of those bodies). The list is fixed by name; nothing else in the model is looked at.
  * Each body's own mass and its own centre of mass are used (mj_jacBodyCom: the body's centre of mass, not the subtree's), and `model.body_subtreemass` and the subtree centres are never read, so
    a body that is attached below (the beaker is a free body of the world, not a child of the hand) cannot enter through a parent.
  * The mass of any other body (the beaker, the plate, the battery, the base) is never read; the experiments/gravity_ff_test.py checks that the torque is unchanged when the beaker's mass changes.
The pose comes from `data.qpos` (the measured joints and the base's pose, so a tilted base is included), copied to a private MjData: the simulation's own state is not touched.
"""

import mujoco
import numpy as np

from src import robot_specs


class ArmGravityFeedforward:
    """tau_ff of both arms and both grippers at the measured pose; `offsets(data)` gives the ctrl offsets tau_ff / kp."""

    def __init__(self, model, arm_act, fing_act, sides=("left", "right")):
        """
        Args:
            model (mujoco.MjModel): The compiled model.
            arm_act (dict): {side: [7 actuator ids]}.
            fing_act (dict): {side: [gripper actuator id]}.
            sides (tuple): The arms. Defaults to both.
        """
        self.model = model
        self.scratch = mujoco.MjData(model)
        self.g = np.asarray(model.opt.gravity, float)
        self.bodies = []                                    # (body id, mass) of the arms' own links, hands and fingers only
        for s in sides:
            for name in robot_specs.ARM_ACTUATOR_SPECS["gravcomp_bodies"]:
                b = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY, f"openarm_{s}_{name}")
                if b < 0:
                    raise ValueError(f"gravity feedforward: body openarm_{s}_{name} not found in the model")
                if model.body_mass[b] > 0:
                    self.bodies.append((int(b), float(model.body_mass[b])))
        ids, dofs = [], []                                  # the actuators and, for each, the dofs whose gravity torque it carries
        for s in sides:
            for a in arm_act[s]:
                ids.append(a)
                dofs.append([int(model.jnt_dofadr[model.actuator_trnid[a, 0]])])
            for a in fing_act[s]:
                ids.append(a)
                dofs.append([int(model.joint(f"openarm_{s}_finger_joint{k}").dofadr[0]) for k in (1, 2)])      # finger 2 follows finger 1 (joint equality): the actuator carries both
        self.ids = np.array(ids)
        self.dofs = dofs
        self.kp = model.actuator_gainprm[self.ids, 0].copy()
        self.lo = np.array([model.jnt_range[model.actuator_trnid[a, 0]][0] for a in ids])
        self.hi = np.array([model.jnt_range[model.actuator_trnid[a, 0]][1] for a in ids])
        self.jac = np.zeros((3, model.nv))
        self.tau = np.zeros(len(ids))

    @classmethod
    def from_model(cls, model, sides=("left", "right")):
        """For tests and scripts that write data.ctrl themselves (not through src/control_loop.py): finds the arm and gripper actuators by name."""
        arm_act = {s: [mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_ACTUATOR, f"{s}_joint{i}_ctrl") for i in range(1, 8)] for s in sides}
        fing_act = {s: [mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_ACTUATOR, f"{s}_gripper_ctrl")] for s in sides}
        return cls(model, arm_act, fing_act, sides)

    def torques(self, data):
        """tau_ff (N m, N for the gripper) of each actuator in `self.ids` at the pose `data.qpos`: the torque that holds the arms' own bodies against gravity."""
        d, m = self.scratch, self.model
        d.qpos[:] = data.qpos
        mujoco.mj_kinematics(m, d)
        mujoco.mj_comPos(m, d)
        W = np.zeros((3, m.nv))
        for b, mass in self.bodies:
            mujoco.mj_jacBodyCom(m, d, self.jac, None, b)
            W += mass * self.jac
        t = -(self.g @ W)                                   # generalized gravity force is m J^T g; the holding torque is its negative
        self.tau = np.array([t[ds].sum() for ds in self.dofs])
        return self.tau

    def apply(self, ctrl, data):
        """Writes into `ctrl` (the ctrl vector of one physics step, targets in it): for the arm and gripper actuators, the target clipped to the joint's range plus tau_ff / kp. The tau_ff is that of
        the pose now (`torques`, computed when called; callers hold one result for a tick with `apply_offsets`)."""
        self.apply_offsets(ctrl, self.torques(data) / self.kp)

    def apply_offsets(self, ctrl, off):
        ctrl[self.ids] = np.clip(ctrl[self.ids], self.lo, self.hi) + off


def for_tests(model):
    """For tests and scripts that write data.ctrl themselves (not through src/control_loop.py): an object whose `apply(ctrl, data)` adds the feedforward to the arm and gripper targets in `ctrl`
    (call it after writing the targets, before every mj_step)."""
    return ArmGravityFeedforward.from_model(model)
