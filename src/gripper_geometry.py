"""The gripper's geometry read from the compiled model: the approach axis, the finger-closing axis and the pad centre, in the tool point frame.

Code generated by Claude

Nothing here is assumed from a naming or axis convention of the model. The closing axis is the direction in which the two finger slide joints move towards each other (their joint axes,
which must be opposed); the approach axis is the direction from the middle of the two finger joint anchors to the tool point (the hand_tcp body), taken perpendicular to the closing axis;
the pad centre is the centre of the contact patch of the two finger pads: along the closing axis midway between the two fingers' inner faces, and in the other two directions the middle of
the patch of collision-geometry vertices that lie within `patch_tol` of each finger's inner face. A different hand frame, finger orientation or finger mesh in a new robot description
therefore changes the result, not the code. The tool point body is found by name (openarm_<side>_hand_tcp) and the fingers through the arm's finger actuators.

Contents:
    gripper_frame(model, side): approach axis, closing axis and pad centre (all in the tool point frame), and the finger opening range.
    grasp_cfg(model, side, base): GRASP_MAP_CFG with those derived entries added, the config the other B2 modules take.
"""

import mujoco
import numpy as np

from src.robot_helpers import arm_ids
from src.task_config import GRASP_MAP_CFG


def _geom_vertices_world(model, data, geom):
    """The vertices of a collision geom in the world (mesh vertices, or the 8 corners of a box)."""
    t = int(model.geom_type[geom])
    R, p = data.geom_xmat[geom].reshape(3, 3), data.geom_xpos[geom]
    if t == mujoco.mjtGeom.mjGEOM_MESH:
        mid = model.geom_dataid[geom]
        V = model.mesh_vert[model.mesh_vertadr[mid]:model.mesh_vertadr[mid] + model.mesh_vertnum[mid]].astype(float)
    elif t == mujoco.mjtGeom.mjGEOM_BOX:
        s = model.geom_size[geom]
        V = np.array([[sx * s[0], sy * s[1], sz * s[2]] for sx in (-1, 1) for sy in (-1, 1) for sz in (-1, 1)])
    else:
        raise NotImplementedError(f"finger geom of type {t}: only mesh and box fingers are supported")
    return V @ R.T + p


def gripper_frame(model, side, patch_tol=0.001):
    """Derives the gripper's axes and pad centre from the model.

    Args:
        model (mujoco.MjModel): The compiled model.
        side (str): "left" or "right".
        patch_tol (float): Vertices of a finger's collision geometry within this distance of its inner face (along the closing axis) form the pad patch, metres. Defaults to 0.001.

    Returns:
        dict: "approach_axis" (3,) and "closing_axis" (3,) unit vectors and "pad_center_in_tcp" (3,) metres, all in the tool point frame (the hand_tcp body); "finger_open_max" (float,
        the finger joints' upper limit, metres); the closing axis points from the first finger towards the second.

    Raises:
        ValueError: If the two finger joints are not opposed slide joints.
    """
    joints = arm_ids(model, side)["finger_jnt"]
    if len(joints) != 2 or any(model.jnt_type[j] != mujoco.mjtJoint.mjJNT_SLIDE for j in joints):
        raise ValueError(f"{side}: expected two finger slide joints")
    tcp = model.body(f"openarm_{side}_hand_tcp").id
    d = mujoco.MjData(model)
    mujoco.mj_kinematics(model, d)
    Rt, pt = d.xmat[tcp].reshape(3, 3), d.xpos[tcp]
    a1, a2 = d.xaxis[joints[0]].copy(), d.xaxis[joints[1]].copy()
    if np.dot(a1, a2) > -0.99:
        raise ValueError(f"{side}: the finger joint axes are not opposed (dot product {np.dot(a1, a2):.3f})")
    e_c = (a2 - a1) / np.linalg.norm(a2 - a1)                      # from finger 1 towards finger 2 (the joints open away from each other)
    mid = 0.5 * (d.xanchor[joints[0]] + d.xanchor[joints[1]])
    v = pt - mid
    v -= (v @ e_c) * e_c
    e_a = v / np.linalg.norm(v)
    e_t = np.cross(e_a, e_c)
    inner = (-a1, -a2)                                              # a finger's opening direction is away from the other: its inner face looks the other way
    c_face, patch = [], []
    for j, inn in zip(joints, inner):
        body = int(model.jnt_bodyid[j])
        geoms = [g for g in range(model.ngeom) if model.geom_bodyid[g] == body and (model.geom_contype[g] or model.geom_conaffinity[g])]
        if not geoms:
            raise ValueError(f"{side}: finger body {model.body(body).name} has no collision geometry")
        V = np.concatenate([_geom_vertices_world(model, d, g) for g in geoms])
        proj = V @ inn
        top = proj.max()
        P = V[proj >= top - patch_tol]
        c_face.append(float(P[0] @ e_c))                            # the inner face's position along the closing axis
        patch.append(P)
    P = np.concatenate(patch)
    ca = np.array([(P @ e_a).min(), (P @ e_a).max()])
    ct = np.array([(P @ e_t).min(), (P @ e_t).max()])
    centre_w = 0.5 * (c_face[0] + c_face[1]) * e_c + ca.mean() * e_a + ct.mean() * e_t
    to_tool = lambda x: Rt.T @ x
    return {"approach_axis": to_tool(e_a), "closing_axis": to_tool(e_c), "pad_center_in_tcp": to_tool(centre_w - pt),
            "finger_open_max": float(max(model.jnt_range[j, 1] for j in joints))}


def grasp_cfg(model, side, base=GRASP_MAP_CFG):
    """Gives the grasp map settings with the gripper geometry of this arm added.

    Args:
        model (mujoco.MjModel): The compiled model.
        side (str): "left" or "right".
        base (dict): The settings (GRASP_MAP_CFG). Defaults to it.

    Returns:
        dict: A copy of `base` with "approach_axis", "closing_axis", "pad_center_in_tcp" and "finger_open_max" from gripper_frame (the entries every B2 module reads).
    """
    return {**base, **gripper_frame(model, side)}
