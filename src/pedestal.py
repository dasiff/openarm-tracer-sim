"""Placeholder pedestal lift actuator, added to the model at load time.

Code generated by Claude

PLACEHOLDER: the real lift hardware is unconfirmed (see robot_specs.PEDESTAL_SPECS). The pedestal is one slide joint (0 collapsed to 0.418 m raised, the updated robot description's).
Same pattern as src/cameras.py: the XML stays untouched and the extra elements are
added through MjSpec before compiling.
"""

import mujoco
import numpy as np

G = 9.81


def add_pedestal_lift(spec, pedestal_specs):
    """Add one position actuator on the pedestal's slide joint (the updated description's single prismatic joint)."""
    (joint,) = pedestal_specs["joints"]
    if spec.joint(joint) is None:
        raise ValueError(f"Pedestal joint '{joint}' not found in model")
    hi = pedestal_specs["range"][1]
    lowest = pedestal_specs["lowest_command"]

    kp, kv, fmax = (pedestal_specs[k] for k in ("kp", "kv", "force_limit"))
    act = spec.add_actuator()
    act.name = pedestal_specs["actuator_name"]
    act.target = joint
    act.trntype = mujoco.mjtTrn.mjTRN_JOINT
    act.gaintype = mujoco.mjtGain.mjGAIN_FIXED
    act.biastype = mujoco.mjtBias.mjBIAS_AFFINE
    act.gainprm[0] = kp
    act.biasprm[:3] = [0.0, -kp, -kv]            # force = kp * (ctrl - q) - kv * qdot
    act.ctrllimited = mujoco.mjtLimited.mjLIMITED_TRUE
    act.ctrlrange = [lowest, hi]
    act.forcelimited = mujoco.mjtLimited.mjLIMITED_TRUE
    act.forcerange = [-fmax, fmax]


def pedestal_load(model, pedestal_specs):
    """Weight the lift carries, from the compiled model's body masses.

    Returns the mass above the joint (the moving pedestal part, the torso, both arms and everything on them) and the force the one actuator must hold: the weight of that mass minus the part
    that gravity compensation takes (none since M185: the arms' gravity is a calculated torque in the arm joints, so the arms load the lift; `body_gravcomp` is 0 on every body).
    """
    (joint,) = pedestal_specs["joints"]
    root = model.joint(joint).bodyid[0]
    m = float(model.body_subtreemass[root])
    carried = 0.0
    for b in range(model.nbody):
        c = b
        while c > 0 and c != root:
            c = int(model.body_parentid[c])
        if c == root:
            carried += float(model.body_mass[b]) * (1.0 - float(model.body_gravcomp[b]))
    return dict(mass_above_joint_kg=m, carried_mass_kg=carried, hold_force_n=carried * G, static_sag_mm=1000.0 * carried * G / pedestal_specs["kp"])
