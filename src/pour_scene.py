"""The pouring scene (design plan §4.2): a second hollow beaker and balls that stand in for the liquid, added to the beaker task's model at load time.

Code generated by Claude

Opt in: task_beaker_hotplate.load_task(pour=POUR_CFG) builds both beakers with no rigid liquid mass (the contents are the balls), adds the second beaker (src/beaker.add_hollow_beaker, the
same glass beaker, with its gripper contact pairs) and the balls (free spheres, `n_balls` of them, stacked on a lattice inside whichever beaker starts full) through MjSpec before compiling, and
places the second beaker and the balls after the task poses are applied. The scene without `pour` is unchanged.

The ball's friction wins over the glass's through the geom priority (MuJoCo takes the higher priority geom's friction and contact softness), so the balls slide on glass, bench and each
other with POUR_CFG["ball_friction"]; the contact is soft and damped (solref damping ratio above 1) so the balls hardly bounce.

Contents:
    draw_setup(cfg, seed): which beaker starts full and how many balls (drawn per demo).
    ball_offsets(n, cfg, beaker_cfg, seed): the starting positions of the balls in the beaker's frame.
    add_pour_objects(spec, pour_cfg, beaker_cfg, task_cfg): the second beaker and the balls, into the spec.
    apply_pour_poses(model, data, pour_cfg, task_cfg): puts the second beaker and the balls where they start (call after apply_task_poses).
    ball_counts(model, data, pour_cfg, beaker_cfg, source, destination): where the balls are (in the source, transferred, spilled).
"""

import math

import mujoco
import numpy as np

from src.beaker import add_hollow_beaker, beaker_dims
from src.task_config import BEAKER_CFG, POUR_CFG, TASK_CFG

BALL_PREFIX = "pour_ball_"


def draw_setup(cfg=POUR_CFG, seed=None):
    """Draws which beaker starts full and how many balls it holds.

    Args:
        cfg (dict): POUR_CFG; "full" and "n_balls" set to None are drawn, others are kept. Defaults to it.
        seed (int or None): Random seed. Defaults to None, cfg["seed"].

    Returns:
        dict: {"full": "first" or "second", "n_balls": int}.
    """
    rng = np.random.default_rng(cfg["seed"] if seed is None else seed)
    full = cfg["full"] if cfg["full"] is not None else ("first", "second")[int(rng.integers(2))]
    n = cfg["n_balls"] if cfg["n_balls"] is not None else int(rng.integers(cfg["n_range"][0], cfg["n_range"][1] + 1))
    return {"full": full, "n_balls": int(n)}


def ball_offsets(n, cfg=POUR_CFG, beaker_cfg=BEAKER_CFG, seed=0):
    """Gives the starting positions of n balls inside a beaker: layers of a square lattice that fits the inside, the odd layers shifted by half a spacing, a tiny random jitter.

    Args:
        n (int): The number of balls.
        cfg (dict): POUR_CFG. Defaults to it.
        beaker_cfg (dict): BEAKER_CFG (the inside's size). Defaults to it.
        seed (int): Seed of the jitter. Defaults to 0.

    Returns:
        numpy.ndarray: Positions (n, 3) in the beaker's frame (origin at the bottom centre), metres.

    Raises:
        ValueError: If the balls do not fit in the beaker's height.
    """
    dim = beaker_dims(beaker_cfg)
    r = cfg["ball_radius"]
    s = 2.05 * r
    usable = dim["r_in"] - 1.05 * r
    rng = np.random.default_rng(seed)
    pts = []
    k = 0
    while len(pts) < n:
        shift = 0.5 * s if k % 2 else 0.0
        g = np.arange(-int(usable / s) - 1, int(usable / s) + 2) * s + shift
        layer = [(x, y) for x in g for y in g if math.hypot(x, y) <= usable]
        layer.sort(key=lambda p: math.hypot(*p))
        z = dim["bottom"] + 1.05 * r + k * s * cfg["layer_gap"]
        if z + r > beaker_cfg["height"]:
            raise ValueError(f"{n} balls do not fit in the beaker (height {beaker_cfg['height'] * 1000:.0f} mm)")
        pts += [(x, y, z) for x, y in layer]
        k += 1
    P = np.array(pts[:n], float)
    return P + rng.uniform(-0.0002, 0.0002, P.shape)


def _bench_top(spec):
    g = spec.geom("bench_top")
    return float(g.pos[2] + g.size[2])


def add_pour_objects(spec, pour_cfg=POUR_CFG, beaker_cfg=BEAKER_CFG, task_cfg=TASK_CFG, setup=None):
    """Adds the second beaker and the balls to the spec (before compiling; the first beaker must have been built already).

    Args:
        spec (mujoco.MjSpec): The scene with the first beaker built.
        pour_cfg (dict): POUR_CFG. Defaults to it.
        beaker_cfg (dict): The beaker configuration used for both beakers (with liquid_mass 0). Defaults to BEAKER_CFG.
        task_cfg (dict): TASK_CFG (where the first beaker is). Defaults to it.
        setup (dict or None): From draw_setup. Defaults to None, drawn from the configuration.

    Returns:
        dict: The setup ("full", "n_balls") that was built.
    """
    setup = setup or draw_setup(pour_cfg)
    top = _bench_top(spec)
    second = spec.worldbody.add_body(name=pour_cfg["second_body"], pos=[pour_cfg["second_xy"][0], pour_cfg["second_xy"][1], top + task_cfg["beaker_settle_clearance"]])
    second.add_freejoint(name=f"{pour_cfg['second_body']}_free")
    second.add_site(name=f"{pour_cfg['second_body']}_base", pos=[0, 0, 0], size=[0.004, 0, 0], rgba=[1, 0, 0, 0], group=4)
    add_hollow_beaker(spec, {**beaker_cfg, "body": pour_cfg["second_body"]})
    xy = task_cfg["beaker_xy"] if setup["full"] == "first" else pour_cfg["second_xy"]
    off = ball_offsets(setup["n_balls"], pour_cfg, beaker_cfg, pour_cfg["seed"])
    for i, o in enumerate(off):
        b = spec.worldbody.add_body(name=f"{BALL_PREFIX}{i}", pos=[xy[0] + o[0], xy[1] + o[1], top + task_cfg["beaker_settle_clearance"] + o[2]])
        b.add_freejoint(name=f"{BALL_PREFIX}{i}_free")
        b.add_geom(name=f"{BALL_PREFIX}{i}_geom", type=mujoco.mjtGeom.mjGEOM_SPHERE, size=[pour_cfg["ball_radius"], 0, 0], mass=pour_cfg["ball_mass"],
                   friction=list(pour_cfg["ball_friction"]), priority=1, solref=list(pour_cfg["ball_solref"]), solimp=list(pour_cfg["ball_solimp"]), rgba=list(pour_cfg["ball_rgba"]))
    return setup


def _beaker_pos(model, data, body):
    return data.xpos[model.body(body).id].copy()


def apply_pour_poses(model, data, pour_cfg=POUR_CFG, task_cfg=TASK_CFG, setup=None):
    """Puts the second beaker and the balls at their starting poses (call after task_beaker_hotplate.apply_task_poses, which places the first beaker and the hotplate).

    Args:
        model (mujoco.MjModel): The compiled model with the pouring objects.
        data (mujoco.MjData): Its data; qpos and qvel of the second beaker and the balls are overwritten, then a forward pass is done.
        pour_cfg (dict): POUR_CFG. Defaults to it.
        task_cfg (dict): TASK_CFG. Defaults to it.
        setup (dict or None): From draw_setup, which beaker is full. Defaults to None, drawn from the configuration (the same draw as at build time).
    """
    setup = setup or draw_setup(pour_cfg)
    mujoco.mj_forward(model, data)
    top = float(data.xpos[model.body("task_hotplate").id][2])             # the hotplate stands on the bench top
    z0 = top + task_cfg["beaker_settle_clearance"]
    j2 = model.joint(f"{pour_cfg['second_body']}_free")
    data.qpos[j2.qposadr[0]:j2.qposadr[0] + 7] = [*pour_cfg["second_xy"], z0, 1, 0, 0, 0]
    data.qvel[j2.dofadr[0]:j2.dofadr[0] + 6] = 0.0
    xy = task_cfg["beaker_xy"] if setup["full"] == "first" else pour_cfg["second_xy"]
    n = sum(1 for b in range(model.nbody) if model.body(b).name.startswith(BALL_PREFIX))
    off = ball_offsets(n, pour_cfg, BEAKER_CFG_NO_LIQUID, pour_cfg["seed"])
    for i, o in enumerate(off):
        j = model.joint(f"{BALL_PREFIX}{i}_free")
        data.qpos[j.qposadr[0]:j.qposadr[0] + 7] = [xy[0] + o[0], xy[1] + o[1], z0 + o[2], 1, 0, 0, 0]
        data.qvel[j.dofadr[0]:j.dofadr[0] + 6] = 0.0
    mujoco.mj_forward(model, data)


BEAKER_CFG_NO_LIQUID = {**BEAKER_CFG, "liquid_mass": 0.0}


def ball_counts(model, data, pour_cfg, beaker_cfg, source, destination):
    """Counts where the balls are: still in the source beaker, transferred into the destination beaker, or neither (spilled).

    A ball is inside a beaker when, in that beaker's frame, it is within the inside radius of the axis and between the bottom and 2 cm above the rim.

    Args:
        model (mujoco.MjModel): The model.
        data (mujoco.MjData): Its data.
        pour_cfg (dict): POUR_CFG.
        beaker_cfg (dict): The beaker configuration (the inside's size).
        source (str): The name of the beaker body the balls started in.
        destination (str): The name of the other beaker body.

    Returns:
        dict: {"in_source", "transferred", "spilled", "total"}.
    """
    dim = beaker_dims(beaker_cfg)
    n = sum(1 for b in range(model.nbody) if model.body(b).name.startswith(BALL_PREFIX))
    pos = np.array([data.xpos[model.body(f"{BALL_PREFIX}{i}").id] for i in range(n)]).reshape(-1, 3)

    def inside(body):
        R = data.xmat[model.body(body).id].reshape(3, 3)
        loc = (pos - data.xpos[model.body(body).id]) @ R
        return (np.hypot(loc[:, 0], loc[:, 1]) < dim["r_in"]) & (loc[:, 2] > 0.0) & (loc[:, 2] < beaker_cfg["height"] + 0.02)

    a, b = inside(source), inside(destination)
    return {"in_source": int(a.sum()), "transferred": int(b.sum()), "spilled": int(n - a.sum() - b.sum()), "total": n}
