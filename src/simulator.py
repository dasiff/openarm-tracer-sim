"""Generic MuJoCo robot simulator — single environment controller for any scene.

RobotSimulator loads a scene file that includes the Tracer mobile base with the OpenArm bimanual arms, adds the parts that are
not in the robot XML at load time (arm and finger position actuators, the optional pedestal lift, the camera neck and the
cameras, all through MjSpec and configured by src/robot_specs.py), compiles the model and offers stepping, resetting and
observation methods. Scene-specific logic does not belong here.

Code generated by Claude
"""

from pathlib import Path
import mujoco
import numpy as np
from src import robot_specs
from src.arm_actuators import add_arm_actuators
from src.cameras import add_cameras, make_offscreen_big_enough
from src.neck import add_neck
from src.pedestal import add_pedestal_lift


class RobotSimulator:
    """Generic simulation controller for the Tracer + OpenArm robot in any scene.

    Works with whatever scene XML you point it at (single_block.xml,
    chemistry_lab.xml, a bare robot, etc.) — nothing here is tied to a
    specific scene's object names. If a scene has objects you want to track
    each step (a block, a beaker, a workbench), name them via `track_bodies`
    instead of adding new methods or subclasses per scene.

    Attributes:
        model (mujoco.MjModel): The compiled model, with the physics timestep set to robot_specs.SIMULATION_TIMESTEP (1/750 s).
        data (mujoco.MjData): The simulation state belonging to `model`.
        model_path (pathlib.Path): Absolute path of the scene file that was loaded.
        track_bodies (list of str): Names of the bodies whose position and velocity are added to get_observation().
    """

    def __init__(self, model_path: str = None, track_bodies: list[str] = None,
                 cameras: list[dict] = None, pedestal_lift: dict = None,
                 neck=True):
        """Loads the scene, adds the actuators, neck and cameras, compiles the model and creates its data.

        The parts are added in this order: the arm and finger position actuators, the pedestal lift, the neck, the cameras. The
        physics timestep is then set to robot_specs.SIMULATION_TIMESTEP (a note is printed if the XML had another one). A summary
        of the loaded model is printed.

        Args:
            model_path (str or pathlib.Path or None): Path to the MuJoCo XML (MJCF) model or scene file. A scene file should
                <include> the robot model at the top level (see learnings-and-workflow notes on <include> placement). Defaults to
                None, which loads the bare combined robot, deps/OpenArm-Combined/combined_robot.xml, with no scene objects.
            track_bodies (list of str or None): Names of bodies in the scene whose position and velocity should be included in
                get_observation() (e.g. ["block"], or ["beaker_1", "beaker_2"] for a chemistry scene). You can always query any
                body on demand with get_body_state(), whether or not it is in this list. Defaults to None (no tracked bodies).
            cameras (list of dict or None): Camera specification dictionaries (robot_specs.CAMERA_SPECS). If given, the cameras
                are injected into the model via MjSpec before compiling, and the offscreen buffer is sized to fit them. Defaults
                to None (no cameras).
            pedestal_lift (dict or None): robot_specs.PEDESTAL_SPECS. If given, the placeholder pedestal lift (stage coupling plus
                one position actuator) is added via MjSpec as the actuator after the robot's 20 actuators, i.e. at index
                20; the neck's actuators, if the neck is on, follow it. Without the neck it is the last actuator. It changes
                the actuator count from 20 to 21. Defaults to None (no pedestal lift).
            neck (bool or dict or None): The SO-101 camera neck (src/neck.py, robot_specs.NECK_SPECS), attached to the torso after
                the pedestal lift and before the cameras (the eagle camera is on the neck). True means robot_specs.NECK_SPECS,
                a dict means those specifications, None or False means no neck (then the eagle camera has no body to sit on:
                pass cameras without it). Defaults to True.

        Raises:
            FileNotFoundError: If the model file does not exist.
        """
        if model_path is None:
            project_root = Path(__file__).parent.parent
            model_path = project_root / "deps/OpenArm-Combined/combined_robot.xml"

        # Sim choice: resolve to an absolute path because MjSpec mesh loading
        # fails on relative paths.
        model_path = Path(model_path).resolve()
        if not model_path.exists():
            raise FileNotFoundError(f"Model not found: {model_path}")

        # Sim choice: the arm/finger position actuators (always), cameras and the pedestal lift
        # are added programmatically so the scene XMLs stay free of them and their numbers live
        # in robot_specs.
        spec = mujoco.MjSpec.from_file(str(model_path))
        add_arm_actuators(spec)
        if pedestal_lift:
            add_pedestal_lift(spec, pedestal_lift)
        if neck:
            add_neck(spec, robot_specs.NECK_SPECS if neck is True else neck)
        if cameras:
            add_cameras(spec, cameras)
        self.model = spec.compile()
        if cameras:
            make_offscreen_big_enough(self.model, cameras)
            # Sim choice: MuJoCo's near clip plane is znear * scene extent, and
            # this scene's extent is ~24 m (-> ~0.24 m near plane), which clips
            # the fingertips ~0.1 m from the wrist cams. Pull it in to ~1 cm.
            self.model.vis.map.znear = 0.0005

        # Sim choice: robot_specs is the single source of truth for the physics
        # rate, whatever the XML says.
        xml_dt = self.model.opt.timestep
        self.model.opt.timestep = robot_specs.SIMULATION_TIMESTEP
        if not np.isclose(xml_dt, robot_specs.SIMULATION_TIMESTEP):
            print(f"  Note: overriding XML timestep {xml_dt:.6g} s with "
                  f"{robot_specs.SIMULATION_TIMESTEP:.6g} s "
                  f"({robot_specs.PHYSICS_HZ} Hz) from robot_specs")
        self.data = mujoco.MjData(self.model)
        self.model_path = model_path
        self.track_bodies = track_bodies or []

        print(f"✓ Loaded model: {model_path.name}")
        print(f"  Bodies: {self.model.nbody}")
        print(f"  Joints: {self.model.njnt}")
        print(f"  Actuators: {self.model.nu}")
        print(f"  Cameras: {self.model.ncam}")

    def step(self):
        """Steps the physics simulation forward by one timestep."""
        mujoco.mj_step(self.model, self.data)

    def reset(self):
        """Resets the simulation data to the model's initial state (time zero, the model's default positions)."""
        mujoco.mj_resetData(self.model, self.data)

    def close(self):
        """Does nothing; present as the clean-up call of the environment interface."""
        pass

    def get_time(self) -> float:
        """Returns the current simulation time.

        Returns:
            float: Time since the last reset, in seconds.
        """
        return self.data.time

    def get_body_state(self, body_name: str) -> dict:
        """Get position and velocity for any named body in the loaded scene.

        This is the generic replacement for the old scene-specific
        get_block_position() / get_block_velocity(). It works for any body
        present in whichever model_path was loaded — a block, a beaker, a
        workbench, anything. If the name isn't in the current scene, MuJoCo
        raises a KeyError, which is the correct failure mode (better than
        silently returning garbage for a body that doesn't exist here).

        Args:
            body_name (str): Name of a body in the loaded model.

        Returns:
            dict: With the keys "position" (numpy.ndarray of 3 values: the body's x, y, z position in the world frame, metres) and
            "velocity" (numpy.ndarray of 6 values: MuJoCo's cvel for the body, the angular velocity in radians per second
            followed by the linear velocity in metres per second, of the body's centre of mass in the world frame). Both are
            copies.

        Raises:
            KeyError: If the model has no body of that name.
        """
        body = self.data.body(body_name)
        return {
            "position": body.xpos.copy(),
            "velocity": body.cvel.copy(),
        }

    def get_observation(self) -> dict:
        """Get full observation: robot state + state of any tracked bodies.

        Which extra bodies show up here depends entirely on `track_bodies`
        passed at construction, so the same method works unchanged whether
        the scene has a block, a beaker, several objects, or nothing extra
        at all. Scene-specific task-completion logic (e.g. "is the block on
        the target") belongs in a Task object that consumes this
        observation, not here.

        Returns:
            dict: With the keys
                "time" (float): Simulation time, in seconds.
                "joint_angles" (numpy.ndarray): Copy of the full position vector qpos, in radians for rotary joints and metres for
                    slide joints (it also holds the free-joint coordinates of the base, if the model has them).
                "joint_velocities" (numpy.ndarray): Copy of the full velocity vector qvel, in radians per second or metres per
                    second.
                "joint_torques" (numpy.ndarray): Copy of the actuator forces as the servos applied them, in newton metres for
                    rotary actuators and newtons for slides and the pedestal lift.
                "ctrl" (numpy.ndarray): Copy of the commanded control vector (target angles or heights for position actuators,
                    wheel torque commands for the motors).
                "<name>_position" and "<name>_velocity" (numpy.ndarray): For every name in `track_bodies`, the "position" and
                    "velocity" entries of get_body_state(name).
        """
        obs = {
            "time": self.data.time,
            "joint_angles": self.data.qpos.copy(),
            "joint_velocities": self.data.qvel.copy(),
            # actual actuator force (N m for rotary joints, N for slides and the pedestal lift), as
            # the servo applied it; "ctrl" is what was commanded (target angles/heights for position
            # actuators, wheel torque commands for the motors)
            "joint_torques": self.data.actuator_force.copy(),
            "ctrl": self.data.ctrl.copy(),
        }
        for name in self.track_bodies:
            state = self.get_body_state(name)
            obs[f"{name}_position"] = state["position"]
            obs[f"{name}_velocity"] = state["velocity"]
        return obs