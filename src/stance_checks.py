def contiguous_runs(ok):
    """Gives the runs of consecutive True values.

    Args:
        ok (sequence of bool): The flags.

    Returns:
        list of tuple: (first index, last index) of every run, in order.
    """
    runs, start = [], None
    for i, v in enumerate(list(ok) + [False]):
        if v and start is None:
            start = i
        elif not v and start is not None:
            runs.append((start, i - 1))
            start = None
    return runs


class OcclusionMeter:
    """How much of the beaker and the hotplate the robot hides from the eagle camera, by pixels (the stance requirement "occlusion").

    Two segmentation renders of the eagle camera (the camera's own resolution): with the scene as it is, and with every geom of the robot (everything under base_link) made fully transparent
    (geoms with alpha 0 are left out of the scene), so the second shows what the objects would show with nothing in front of them. The hidden share of an object is 1 - visible pixels / pixels
    without the robot. The transparent copy of the model and the two renderers are made on first use and kept; the scene's geometry must not change afterwards (poses in the data may).

    Attributes:
        model (mujoco.MjModel): The compiled model.
        targets (dict): {"beaker": body id, "hotplate": body id} of the objects measured.
    """

    def __init__(self, model, camera="eagle_cam", targets=(("beaker", "task_beaker"), ("hotplate", "task_hotplate")), occluders="robot", extra_geoms=()):
        """Args:
            model (mujoco.MjModel): The compiled model.
            camera (str): The camera. Defaults to "eagle_cam".
            targets (tuple): (name, body name) of the objects measured.
            occluders (str): "robot" (the default and the old behaviour: only the robot is taken away in the reference render, so only the robot's hiding is counted) or "all" (R2i,
                decisions-log M139: the robot and the `extra_geoms` are taken away, so anything of those that hides a target counts). Taking the whole room away instead would change the
                pixel count of the beaker's thin walls (about 3 %: the depth buffer's resolution depends on what else is in the picture), so the static furniture stays in the reference.
            extra_geoms (iterable of int): Geoms (besides the robot's) that count as occluders with "all": the object slots of src/full_check.py (the unknown objects of the table).
        """
        self.model, self.camera, self.occluders, self.extra_geoms = model, camera, occluders, set(int(g) for g in extra_geoms)

        self.targets = {name: model.body(body).id for name, body in targets}
        self._free_model, self._renderers = None, {}
        bname = lambda g: model.body(int(model.geom_bodyid[g])).name
        arm = [g for g in range(model.ngeom) if bname(g).startswith(("openarm_left_", "openarm_right_")) and not bname(g).endswith("link0")]       # the arms (the shoulder mounts link0 are not moving parts)
        self.arm_geoms = np.array(arm, dtype=int)
        self.hand_geoms = np.array([g for g in arm if "hand" in bname(g) or "finger" in bname(g)], dtype=int)
        spec = next(c for c in robot_specs.CAMERA_SPECS if c["name"] == camera)
        self.width, self.height = spec["resolution"]

    def _renderer(self, key):
        if key not in self._renderers:
            if key == "free" and self._free_model is None:
                m = self.model
                root = m.body("base_link").id

                def under_root(b):
                    while b > 0:
                        if b == root:
                            return True
                        b = int(m.body_parentid[b])
                    return False

                self._free_model = copy.copy(m)
                for g in range(m.ngeom):
                    if under_root(int(m.geom_bodyid[g])) or (self.occluders == "all" and g in self.extra_geoms):
                        self._free_model.geom_rgba[g, 3] = 0.0
            r = mujoco.Renderer(self._free_model if key == "free" else self.model, self.height, self.width)
            r.enable_segmentation_rendering()
            self._renderers[key] = r
        return self._renderers[key]

    def _count(self, key, data):
        r = self._renderer(key)
        r.update_scene(data, camera=self.camera)
        seg = r.render()
        ids, types_ = seg[:, :, 0], seg[:, :, 1]
        is_geom = types_ == int(mujoco.mjtObj.mjOBJ_GEOM)
        geom_body = np.asarray(self.model.geom_bodyid)
        gids = np.where(is_geom, ids, 0)
        out = {name: int((is_geom & np.isin(gids, np.nonzero(geom_body == b)[0])).sum()) for name, b in self.targets.items()}
        if key == "scene":                                                      # the arms' share of the image (with the robot in the scene)
            arm, hand = is_geom & np.isin(gids, self.arm_geoms), is_geom & np.isin(gids, self.hand_geoms)
            out["_arm_mask"], out["arm_px"], out["hand_px"] = arm, int(arm.sum()), int(hand.sum())
            out["_pixels"] = int(ids.size)
        return out

    def measure(self, data, masks=False):
        """Measures the occlusion and the arm coverage for the state in `data` (the neck must be at the pose to be judged).

        Args:
            data (mujoco.MjData): The data with kinematics up to date (mj_forward).
            masks (bool): Also return the arms' pixel mask ("arm_mask", bool (height, width)). Defaults to False.

        Returns:
            dict: "<name>_px" (pixels with the robot), "<name>_px_free" (without) and "<name>_hidden_frac" for the beaker and the hotplate; "arm_frac" and "hand_frac": the share of the image
            covered by the arms (every moving arm part, hands included) and by the hands alone (hand and fingers).
        """
        with_robot, free = self._count("scene", data), self._count("free", data)
        out = {"arm_frac": with_robot["arm_px"] / with_robot["_pixels"], "hand_frac": with_robot["hand_px"] / with_robot["_pixels"]}
        if masks:
            out["arm_mask"] = with_robot["_arm_mask"]
        for name in self.targets:
            out[f"{name}_px"], out[f"{name}_px_free"] = with_robot[name], free[name]
            out[f"{name}_hidden_frac"] = 1.0 - with_robot[name] / max(free[name], 1)
        return out

    def close(self):
        for r in self._renderers.values():
            r.close()
        self._renderers = {}


def occlusion_ok(occ, limits=STANCE_REQUIREMENTS["occlusion_max_hidden"]):
    """True if the measured hidden shares are within the limits (a share of exactly 0 for the beaker: not one pixel hidden)."""
    return all(occ[f"{name}_hidden_frac"] <= lim + (1e-12 if lim == 0.0 else 0.0) for name, lim in limits.items())


class StanceChecks:
    """The two stance checks, on a private copy of the scene's state.

    Attributes:
        model (mujoco.MjModel): The compiled model.
        d (mujoco.MjData): Scratch data: the scene's state at construction (the objects placed), changed by every call.
        base_z (float): The base origin's resting height above the floor (src/stance_finder.robot_geometry).
        home (dict): {"left": 7 angles, "right": 7 angles}, the home pose with the configured variation.
    """

    def __init__(self, model, data, base_z, task_cfg=TASK_CFG, finger_open=STAGING_CFG["finger_open"], points_fn=framing_points, occluders="robot", extra_geoms=()):
        """Builds the checks.

        Args:
            model (mujoco.MjModel): The compiled model of the scene with the robot.
            data (mujoco.MjData): Its data with the objects in place (the beaker is a free body: its pose is in qpos).
            base_z (float): The base origin's resting height above the floor, metres.
            task_cfg (dict): The task configuration (the home pose and the neck framing points come from it). Defaults to TASK_CFG.
            finger_open (float): The finger opening at home, metres. Defaults to STAGING_CFG["finger_open"].
            points_fn (callable): points_fn(model, data) -> {name: world point}, the points the neck must frame. Defaults to framing_points.
            occluders (str): "robot" (the default, the old behaviour) or "all": what the occlusion check counts as hiding a target (see OcclusionMeter).
            extra_geoms (iterable of int): The geoms that count as occluders besides the robot's with "all".
        """
        self.model, self.base_z, self.finger_open, self.points_fn, self.task_cfg, self.occluders = model, float(base_z), finger_open, points_fn, task_cfg, occluders
        self.extra_geoms = tuple(extra_geoms)
        self.d = mujoco.MjData(model)
        self.d.qpos[:] = data.qpos
        self.home = home_targets(model, task_cfg)
        self.q_scene = data.qpos.copy()
        root = model.body("base_link").id

        def under_root(b):
            while b > 0:
                if b == root:
                    return True
                b = int(model.body_parentid[b])
            return False

        bname = lambda g: model.body(int(model.geom_bodyid[g])).name
        self.arm_geoms = [g for g in range(model.ngeom) if model.geom_group[g] == 3 and bname(g).startswith("openarm_") and not bname(g).endswith("link0")]
        self.hand_geoms = [g for g in self.arm_geoms if "hand" in bname(g) or "finger" in bname(g)]
        self.world_geoms = [g for g in range(model.ngeom) if (model.geom_contype[g] or model.geom_conaffinity[g]) and int(model.geom_type[g]) != int(mujoco.mjtGeom.mjGEOM_PLANE)
                            and not under_root(int(model.geom_bodyid[g]))]
        self.ft = np.zeros(6)
        self.meter = None

    def place(self, stance):
        """Puts the robot at a stance with both arms at home, the fingers open and the neck at its drive pose (kinematics only).

        Args:
            stance (tuple): (x, y, yaw, pedestal command): the base origin in the world (metres), its heading (radians) and the pedestal command (metres).
        """
        m, d = self.model, self.d
        x, y, yaw, q = stance
        d.qpos[:] = self.q_scene
        d.qpos[0:7] = [x, y, self.base_z, *yaw_to_quat(yaw)]
        for jn in robot_specs.PEDESTAL_SPECS["joints"]:
            d.qpos[m.joint(jn).qposadr[0]] = q
        for sd in ("left", "right"):
            ids = arm_ids(m, sd)
            for a, v in zip(ids["qadr"], self.home[sd]):
                d.qpos[a] = v
            for j in ids["finger_jnt"]:
                d.qpos[m.jnt_qposadr[j]] = self.finger_open
        set_neck_pose(m, d, robot_specs.NECK_SPECS)
        mujoco.mj_kinematics(m, d)

    def home_clearance(self, stance, look=0.3):
        """The smallest distance from the arms at home to the scene's other geoms (the bench, the hotplate, the beaker and every other piece of the scene).

        Args:
            stance (tuple): (x, y, yaw, pedestal command), see place().
            look (float): Distances are looked up to this, metres. Defaults to 0.3 (so the result is at most 0.3).

        Returns:
            dict: "arms" (smallest distance of any moving arm part, metres, negative: penetration), "hands" (the same for the hand and fingers only), "arms_pair" and "hands_pair"
            (the geom names of the closest pair, "arm geom vs scene geom").
        """
        self.place(stance)
        m, d = self.model, self.d
        out = {}
        for key, geoms in (("arms", self.arm_geoms), ("hands", self.hand_geoms)):
            best, pair = look, ""
            for a in geoms:
                for b in self.world_geoms:
                    if np.linalg.norm(d.geom_xpos[a] - d.geom_xpos[b]) - m.geom_rbound[a] - m.geom_rbound[b] > best:
                        continue
                    v = mujoco.mj_geomDistance(m, d, a, b, look, self.ft)
                    if v < best:
                        best, pair = v, f"{m.geom(a).name} vs {m.geom(b).name}"
            out[key], out[key + "_pair"] = float(best), pair
        return out

    def neck_spread(self, stance, n=8, noise=1.7e-3, seed=1):
        """How much the neck framing solve moves when the arms are perturbed: the largest change of any neck joint over n perturbed solves, radians.

        The perturbation is the one of experiments/neck_once_test.py (every arm joint of both arms gets a draw of `noise` rad (0.1 degree) times a standard normal, the points are
        re-read from the perturbed state); the first four draws are the test's own, so a stance that passes here with the test's limit passes the test.

        Args:
            stance (tuple): (x, y, yaw, pedestal command), see place().
            n (int): The number of perturbed solves. Defaults to 8.
            noise (float): The standard deviation of the joint noise, radians. Defaults to 1.7e-3.
            seed (int): The random seed. Defaults to 1 (the test's).

        Returns:
            dict: "spread" (largest joint change over all draws, radians), "spread_test_draws" (over the first four draws, the test's own) and "targets" (the unperturbed solution, joint name -> radians).
            (The eagle camera's view of the beaker and the hotplate is judged by occlusion(), by pixels.)
        """
        self.place(stance)
        m, d = self.model, self.d
        t1, _ = frame_points(m, d, self.points_fn(m, d))
        rng = np.random.default_rng(seed)
        q0 = d.qpos.copy()
        worst, worst4 = 0.0, 0.0
        for k in range(n):
            d.qpos[:] = q0
            for sd in ("left", "right"):
                for i in range(1, 8):
                    d.qpos[m.joint(f"openarm_{sd}_joint{i}").qposadr[0]] += noise * rng.standard_normal()
            mujoco.mj_kinematics(m, d)
            tp, _ = frame_points(m, d, self.points_fn(m, d))
            c = max(abs(tp[j] - t1[j]) for j in t1)
            worst = max(worst, c)
            if k < 4:
                worst4 = max(worst4, c)
        d.qpos[:] = q0
        mujoco.mj_kinematics(m, d)
        d.qpos[:] = q0
        mujoco.mj_kinematics(m, d)
        return {"spread": float(worst), "spread_test_draws": float(worst4), "targets": {k: float(v) for k, v in t1.items()}}

    def beaker_on_hotplate_clearance(self, stance, look=0.3):
        """The smallest distance from the arms at home to the beaker standing on the hotplate (information: the home pose must not collide with a beaker that has been placed).

        Args:
            stance (tuple): (x, y, yaw, pedestal command), see place().
            look (float): Distances are looked up to this, metres. Defaults to 0.3.

        Returns:
            float or None: The distance in metres (negative: the arm would be inside the beaker), or None if the scene has no beaker or hotplate body.
        """
        m, d = self.model, self.d
        try:
            beaker, plate = m.body("task_beaker"), m.geom("task_hotplate_top_plate")
        except KeyError:
            return None
        self.place(stance)
        top = float(d.geom_xpos[plate.id][2] + m.geom_size[plate.id][2])
        jq = m.joint("task_beaker_free").qposadr[0]
        d.qpos[jq:jq + 7] = [d.geom_xpos[plate.id][0], d.geom_xpos[plate.id][1], top + 0.002, 1, 0, 0, 0]
        mujoco.mj_kinematics(m, d)
        beaker_geoms = [g for g in range(m.ngeom) if int(m.geom_bodyid[g]) == beaker.id and (m.geom_contype[g] or m.geom_conaffinity[g])]
        best = look
        for a in self.arm_geoms:
            for b in beaker_geoms:
                best = min(best, mujoco.mj_geomDistance(m, d, a, b, look, self.ft))
        return float(best)

    def framing_slack(self, stance, grippers=True):
        """The framing slack at a stance: the largest worst-case margin any neck pose can give for the points the neck must frame, as a fraction of the image.

        Args:
            stance (tuple): (x, y, yaw, pedestal command), see place().
            grippers (bool): Whether both grippers' points (tool point, hand, finger tips) are among the points, as in the staging. Defaults to True.

        Returns:
            dict: "slack" (fraction of the image; the requirement is STANCE_REQUIREMENTS["framing_min_slack"]), "limit" (the name of the point that limits it) and "free" (whether that neck
            pose is collision-free).
        """
        self.place(stance)
        sim = types.SimpleNamespace(model=self.model, data=self.d)
        pts = dict(self.points_fn(self.model, self.d))
        if not grippers:
            pts = {k: v for k, v in pts.items() if "gripper" not in k}
        slack, who, free = best_margin(sim, pts)
        return {"slack": float(slack), "limit": who, "free": bool(free)}

    def occlusion(self, stance, targets=None):
        """The pixel-area occlusion of the beaker and the hotplate at a stance, with the neck at its framing pose.

        Args:
            stance (tuple): (x, y, yaw, pedestal command), see place().
            targets (dict or None): The neck's framing pose (joint name -> radians), e.g. from neck_spread(); None: solved here.

        Returns:
            dict: OcclusionMeter.measure's.
        """
        if targets is None:
            targets = self.neck_spread(stance, n=1)["targets"]
        self.place(stance)
        set_neck_pose(self.model, self.d, robot_specs.NECK_SPECS, [targets[n] for n in robot_specs.NECK_SPECS["active_joints"]])
        mujoco.mj_forward(self.model, self.d)
        if self.meter is None:
            self.meter = OcclusionMeter(self.model, occluders=self.occluders, extra_geoms=self.extra_geoms)
        return self.meter.measure(self.d)

    def requirements(self, stance, req=STANCE_REQUIREMENTS, n_spread=8):
        """All the requirements of the stance checks at a stance (not the reach tolerance, which comes from the finder), cheap ones first; later ones are skipped when an earlier one fails.

        Args:
            stance (tuple): (x, y, yaw, pedestal command), see place().
            req (dict): The limits. Defaults to STANCE_REQUIREMENTS.
            n_spread (int): The number of perturbed solves of the neck spread. Defaults to 8.

        Returns:
            dict: "home_clearance" (home_clearance's), "placed_beaker_mm" (the arms' distance to a beaker on the hotplate, millimetres, or None if the scene has none), "neck" (neck_spread's, or None
            if skipped), "occlusion" (or None), "framing" (framing_slack's, or None), "ok" (every requirement met), "failed" (the names of the requirements not met or not reached:
            "home_clearance", "placed_beaker", "neck_spread", "occlusion", "framing").
        """
        out = {"home_clearance": self.home_clearance(stance), "placed_beaker_mm": None, "neck": None, "occlusion": None, "framing": None, "failed": []}
        pb = self.beaker_on_hotplate_clearance(stance)
        out["placed_beaker_mm"] = None if pb is None else 1000 * pb
        if out["home_clearance"]["arms"] < req["home_min_clearance"]:
            out["failed"].append("home_clearance")
        if pb is not None and pb < req["placed_beaker_min_clearance"]:
            out["failed"].append("placed_beaker")
        if not out["failed"]:                                                    # the slow checks only where the cheap ones pass
            out["neck"] = self.neck_spread(stance, n=n_spread)
            if out["neck"]["spread"] > req["neck_max_spread"]:
                out["failed"].append("neck_spread")
            else:
                out["occlusion"] = self.occlusion(stance, out["neck"]["targets"])
                if not occlusion_ok(out["occlusion"], req["occlusion_max_hidden"]):
                    out["failed"].append("occlusion")
                else:
                    out["framing"] = self.framing_slack(stance)
                    if out["framing"]["slack"] < req["framing_min_slack"]:
                        out["failed"].append("framing")
        out["ok"] = not out["failed"]
        return out
