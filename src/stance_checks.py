"""Checks of a candidate stance that the stance finder's verification of its top candidates runs (design plan §3.4): the home pose clearance and the neck framing repeatability.

Code generated by Claude

The finder (src/stance_finder.py) and the IK verification (experiments/stance_sensitivity.py) say where the task points can be reached. Two more things must hold at the stance for the staging
to work (David 2026-10-19), and both depend on the pedestal height, so the height comes out of the search for any scene instead of being typed into the config:
  home pose clearance      with both arms at the home pose (the zombie pose the robot stands in and drives in, design plan §1), every moving arm part, the fingers and hand included, stays at least
                           min_clearance (40 mm, the home_pose_test requirement) from the bench, the hotplate and every other object and piece of furniture of the scene;
  neck framing repeatability  the neck framing solve (src/neck_framing.py) moves no neck joint by more than max_spread (0.06 rad, the neck_once_test limit) when the arms are perturbed by
                           0.1 degree: the framing is a flat-valley problem at some stances (its answer can jump along the lift / elbow / wrist direction), and the neck must not jump between two
                           staging runs that differ by noise.

  placed beaker     with both arms at home, every moving arm part stays at least 40 mm from a beaker resting on the hotplate (beaker_on_hotplate_clearance; David 2026-10-19: a requirement,
                    not only a report).

Two more requirements are measured on the eagle camera's image (David 2026-10-19; the limits are in task_config.STANCE_REQUIREMENTS and are the same in the stance finder, the home pose search
and home_pose_test):
  framing slack     with the neck at the best pose it can take, the beaker's and hotplate's corners and both grippers (tool point, hand, finger tips) are at least 10 % of the image from every
                    edge (neck_framing.best_margin; the neck framing itself only has to reach the 10 %, this says how much room there really is);
  occlusion         with the neck at its framing pose, the robot hides none of the beaker's pixels and at most 20 % of the hotplate's (OcclusionMeter: a segmentation render of the eagle camera
                    with the robot and one with the robot invisible; this replaces the old 18-point ray test, which let a hand hide a quarter of the hotplate).

A preference, not a requirement (David 2026-10-20): the arm coverage, the share of the eagle image's pixels the robot's arms cover (hands protruding into the image); the same render gives it.
The finder ranks by it after the requirements and the pedestal range, and the home pose search minimizes it once the margins are comfortable.

Contents:
    OcclusionMeter: the pixel-area occlusion of the beaker and the hotplate, and the arm coverage, for a model and its data.
    StanceChecks: build once per scene; home_clearance(stance), neck_spread(stance), framing_slack(stance), occlusion(stance), beaker_on_hotplate_clearance(stance) and requirements(stance).
    contiguous_runs(ok): the runs of consecutive True values of a boolean list, as (first, last) index pairs.
"""

