"""The stance finder core (design plan §3.4): where can the robot stand so that every task point is reachable, ranked by how far from the edge of the valid region.

Code generated by Claude

Given task points (world positions, each labelled "left", "right" or "either" arm, optionally with a required approach bin), the grasp maps (src/reach_map.ReachMap per arm and bin) and the
layered furniture map (src/furniture_map.FurnitureMap), it works on a floor grid around the points. For a heading and a pedestal height, a point is reachable by an arm from a floor spot p
when the point, expressed in that arm's shoulder frame, lies in a reachable cube of the map; seen from the point that is the map's horizontal slice at the point's height, flipped around the
point and turned by the heading, so the region of valid spots for all points is the overlap of the flipped slices (done here by gathering: for every floor cell the point's position relative to
the shoulder is looked up in the slice). The region loses the cells the furniture blocks, and is made robust to the heading error by intersecting it with the regions at the heading plus and
minus a small angle. The score of a spot is its distance to the nearest edge of the valid region (a distance transform; the edges include the borders of holes in the maps and the
furniture); because the region is the overlap of all the points' regions this is the minimum over the points. For each spot the valid pedestal heights are recorded and the middle of the
contiguous range around the best one is chosen. Stances at which both arms reach every point rank above stances at which only one does (the VLA chooses the hand, so a stance should work for
either). The output lists ranked, spread-out stances; the arm rule of the demo generator (design plan §5) is arm_for(): the arm with the better score rounded to 1 cm, ties to the left.

Floor grids are indexed [iy, ix] as in src/furniture_map.py. Verification of the top stances (IK along the paths, link-to-furniture checks, B2.12) is not part of this module.

Contents:
    robot_geometry(model): shoulders, mast, base height and footprint read from the model.
    find_stances(points, maps, furniture, robot, ...): the search.
    region_scores(...): the valid-region scores of one heading (for inspection and tests).
    arm_for(stance, resolution): the arm the generator picks at a stance.
"""

import math

import mujoco
import numpy as np
from scipy import ndimage

from src import robot_specs
from src.arm_kinematics import arm_chain, shoulder_origin
from src.furniture_map import footprint_polygon
from src.task_config import STANCE_CFG


def robot_geometry(model):
    """Reads what the stance finder needs to know about the robot from the compiled model.

    Args:
        model (mujoco.MjModel): The compiled model (with the pedestal lift joints; the battery is part of the footprint if the model has it).

    Returns:
        dict: "shoulder" ({"left": (x, y, z), "right": ...}: each arm's shoulder in the torso frame, metres), "torso_z0" (the torso frame's height above the base origin at pedestal
        command 0), "lift_factor" (torso height change per metre of stage command: both stages move), "base_z" (the base origin's resting height above the floor), "footprint" (convex
        polygon (K, 2) of the base and the battery in the base frame).
    """
    d = mujoco.MjData(model)
    root, torso = model.body("base_link").id, model.body("openarm_body_link0").id

    def torso_height(q):
        for jn in robot_specs.PEDESTAL_SPECS["joints"]:
            d.qpos[model.joint(jn).qposadr[0]] = q
        mujoco.mj_kinematics(model, d)
        return float(d.xpos[torso][2] - d.xpos[root][2])

    z0, z1 = torso_height(0.0), torso_height(-0.1)
    for jn in robot_specs.PEDESTAL_SPECS["joints"]:
        d.qpos[model.joint(jn).qposadr[0]] = 0.0
    mujoco.mj_kinematics(model, d)
    bodies = [root] + ([model.body("battery").id] if any(model.body(b).name == "battery" for b in range(model.nbody)) else [])
    bc = robot_specs.BASE_CONTACT_SPECS
    base_z = -min(v[2] for v in bc["points"].values()) + bc["radius"]
    return {"shoulder": {sd: shoulder_origin(arm_chain(model, sd)) for sd in ("left", "right")}, "torso_z0": z0, "lift_factor": (z0 - z1) / 0.1, "base_z": float(base_z),
            "footprint": footprint_polygon(model, d, bodies)}


def _torso_z(robot, q):
    return robot["base_z"] + robot["torso_z0"] + robot["lift_factor"] * q


def _pick_height(S, valid):
    """For each cell, the middle of the contiguous run of valid pedestal heights around the best one.

    Args:
        S (numpy.ndarray): Scores (nq, ncells), zero where not valid.
        valid (numpy.ndarray): Bool (nq, ncells).

    Returns:
        tuple: (index of the chosen height (ncells,), lowest valid index of the run, highest, the score at the chosen height, whether the cell has any valid height).
    """
    nq, n = S.shape
    cells = np.arange(n)
    best = S.argmax(axis=0)
    lo, hi = best.copy(), best.copy()
    for _ in range(nq):
        lo = np.where((lo > 0) & valid[np.maximum(lo - 1, 0), cells], lo - 1, lo)
        hi = np.where((hi < nq - 1) & valid[np.minimum(hi + 1, nq - 1), cells], hi + 1, hi)
    mid = (lo + hi) // 2
    return mid, lo, hi, S[mid, cells], valid.any(axis=0)


def _region(points, arm, maps, furniture, robot, theta, qs, X, Y, blocked_w, cfg_res):
    """The valid floor cells for one arm at one heading, for every pedestal command: (nq, ncells) bool."""
    nq = len(qs)
    V = np.ones((nq, X.size), bool)
    sx, sy, sz = robot["shoulder"][arm]
    c, s = math.cos(theta), math.sin(theta)
    zt = np.array([_torso_z(robot, q) + sz for q in qs])
    for pt in points:
        if pt["arm"] not in (arm, "either"):
            return np.zeros_like(V)
        keys = [(arm, pt["bin"])] if pt["bin"] is not None else [k for k in maps if k[0] == arm]
        rmaps = [maps[k] for k in keys if k in maps]
        if not rmaps:
            return np.zeros_like(V)
        P = np.asarray(pt["p"], float)
        dx, dy = (P[0] - X).ravel(), (P[1] - Y).ravel()
        rx, ry = c * dx + s * dy - sx, -s * dx + c * dy - sy                  # the point in the shoulder frame (xy): the torso frame is turned by the heading
        zr = P[2] - zt                                                        # (nq,) height of the point above the shoulder, per pedestal command
        any_q = np.zeros_like(V)
        for rm in rmaps:
            ix = np.floor((rx - rm.origin[0]) / rm.cube).astype(int)
            iy = np.floor((ry - rm.origin[1]) / rm.cube).astype(int)
            inb = (ix >= 0) & (ix < rm.cubes.shape[0]) & (iy >= 0) & (iy < rm.cubes.shape[1])
            for qi in range(nq):
                iz = int(np.floor((zr[qi] - rm.origin[2]) / rm.cube))
                if 0 <= iz < rm.cubes.shape[2]:
                    m = np.zeros(X.size, bool)
                    m[inb] = rm.cubes[ix[inb], iy[inb], iz]
                    any_q[qi] |= m
        V &= any_q
        if not V.any():
            return V
    V &= ~blocked_w.ravel()[None, :]
    return V


def _window(furniture, points, cfg, centre):
    """The floor window searched: cell bounds and the cell centre coordinates (X, Y), each (wy, wx)."""
    res = furniture.res
    P = np.array([pt["p"] for pt in points], float)
    cxy = P[:, :2].mean(axis=0) if centre is None else np.asarray(centre, float)
    half = int(round(cfg["window"] / res))
    cx, cy = int(round((cxy[0] - furniture.origin[0]) / res)), int(round((cxy[1] - furniture.origin[1]) / res))
    ix0, ix1 = max(cx - half, 0), min(cx + half, furniture.shape[1])
    iy0, iy1 = max(cy - half, 0), min(cy + half, furniture.shape[0])
    X = furniture.origin[0] + (np.arange(ix0, ix1) + 0.5) * res
    Y = furniture.origin[1] + (np.arange(iy0, iy1) + 0.5) * res
    X, Y = np.meshgrid(X, Y)
    return (iy0, iy1, ix0, ix1), X, Y


def _heading_scores(points, arms, maps, furniture, robot, theta, qs, X, Y, win, cfg):
    """Scores of every floor cell of the window for each allowed arm at a heading, robust to the heading error: {arm: (nq, ncells)}."""
    iy0, iy1, ix0, ix1 = win
    res = furniture.res
    delta = math.radians(cfg["heading_robust_deg"])
    thetas = [theta] if delta == 0 else [theta - delta, theta, theta + delta]
    region = {a: np.ones((len(qs), X.size), bool) for a in arms}
    for th in thetas:
        blocked = furniture.blocked(th, robot["footprint"])[iy0:iy1, ix0:ix1]
        for a in arms:
            region[a] &= _region(points, a, maps, furniture, robot, th, qs, X, Y, blocked, res)
    S = {}
    for a in arms:
        Sa = np.zeros((len(qs), X.size))
        for qi in range(len(qs)):
            if region[a][qi].any():
                Sa[qi] = (ndimage.distance_transform_edt(np.pad(region[a][qi].reshape(X.shape), 1, constant_values=False))[1:-1, 1:-1] * res).ravel()
        S[a] = Sa
    return S


def _allowed_arms(points):
    return [a for a in ("left", "right") if all(pt["arm"] in (a, "either") for pt in points)]


def region_scores(points, maps, furniture, robot, heading, pedestal_qs, cfg=STANCE_CFG, centre=None):
    """Gives the valid-region scores of one heading (what find_stances ranks), for inspection and tests.

    Args:
        points (list of dict): The task points, as in find_stances.
        maps (dict): {(side, bin): ReachMap}.
        furniture (src.furniture_map.FurnitureMap): The furniture map.
        robot (dict): From robot_geometry.
        heading (float): The heading, radians.
        pedestal_qs (iterable of float): The pedestal commands.
        cfg (dict): STANCE_CFG. Defaults to it.
        centre (array-like or None): The window's centre. Defaults to None, the mean of the points' xy.

    Returns:
        tuple: (X, Y, S): the window's cell centre coordinates (wy, wx) and {arm: scores (nq, wy, wx)} in metres: the distance of each valid cell to the nearest edge of that arm's valid
        region, 0 where the cell is not valid.
    """
    win, X, Y = _window(furniture, points, cfg, centre)
    qs = np.asarray(sorted(pedestal_qs), float)
    S = _heading_scores(points, _allowed_arms(points), maps, furniture, robot, heading, qs, X, Y, win, cfg)
    return X, Y, {a: v.reshape(len(qs), *X.shape) for a, v in S.items()}


def find_stances(points, maps, furniture, robot, cfg=STANCE_CFG, headings=None, pedestal_qs=None, centre=None):
    """Finds and ranks stances for a set of task points.

    Args:
        points (list of dict): The task points: {"p": (x, y, z) world metres, "arm": "left" | "right" | "either", "bin": approach bin or None (any bin)}.
        maps (dict): {(side, bin): ReachMap} (src/reach_map.ReachMap).
        furniture (src.furniture_map.FurnitureMap): The layered furniture map.
        robot (dict): From robot_geometry (or made up for a synthetic case).
        cfg (dict): STANCE_CFG. Defaults to it.
        headings (iterable of float or None): Headings to search, radians. Defaults to None, every cfg["heading_step_deg"] degrees around the circle.
        pedestal_qs (iterable of float or None): Pedestal stage commands to search, metres. Defaults to None, from the lowest command to 0 in steps of cfg["pedestal_step"].
        centre (array-like or None): The centre (x, y) of the searched floor window, metres. Defaults to None, the mean of the points' xy.

    Returns:
        list of dict: Ranked, spread-out stances (best first, at most cfg["max_stances"]), each with "x", "y", "heading" (radians), "heading_deg", "q" (the chosen pedestal command), "q_lo",
        "q_hi" (the valid contiguous range around it), "torso_z" (the torso frame's height at q), "arm" ("both", "left" or "right": the arms that reach every point), "score_left" and
        "score_right" (distance to the region's edge at the chosen pedestal command, metres; None for an arm that does not reach), "score" (the ranking score: the smaller of the two for
        "both") and "tier" (1 for both arms, 0 for one).
    """
    if headings is None:
        headings = np.radians(np.arange(0.0, 360.0, cfg["heading_step_deg"]))
    if pedestal_qs is None:
        pedestal_qs = np.arange(robot_specs.PEDESTAL_SPECS["lowest_command"], 1e-9, cfg["pedestal_step"])
    qs = np.asarray(sorted(pedestal_qs), float)
    win, X, Y = _window(furniture, points, cfg, centre)
    Xr, Yr = X.ravel(), Y.ravel()
    arms = _allowed_arms(points)
    cand = []
    for theta in headings:
        S = _heading_scores(points, arms, maps, furniture, robot, theta, qs, X, Y, win, cfg)
        combos = []
        if len(arms) == 2:
            Sb = np.minimum(S["left"], S["right"])
            combos.append(("both", Sb, Sb > 0))
        combos += [(a, S[a], S[a] > 0) for a in arms]
        for name, Sc, valid in combos:
            mid, lo, hi, score, ok = _pick_height(Sc, valid)
            idx = np.nonzero(ok & (score > 0))[0]
            if len(idx) == 0:
                continue
            for c in idx[np.argsort(-score[idx])[:300]]:
                q = float(qs[mid[c]])
                sl = float(S["left"][mid[c], c]) if "left" in S and S["left"][mid[c], c] > 0 else None
                sr = float(S["right"][mid[c], c]) if "right" in S and S["right"][mid[c], c] > 0 else None
                cand.append({"x": float(Xr[c]), "y": float(Yr[c]), "heading": float(theta), "heading_deg": math.degrees(theta), "q": q, "q_lo": float(qs[lo[c]]), "q_hi": float(qs[hi[c]]),
                             "torso_z": _torso_z(robot, q), "arm": name, "score_left": sl, "score_right": sr, "score": float(score[c]), "tier": 1 if name == "both" else 0})
    cand.sort(key=lambda c: (-c["tier"], -c["score"], -(c["q_hi"] - c["q_lo"])))
    out = []
    for c in cand:
        if len(out) >= cfg["max_stances"]:
            break
        if all(math.hypot(c["x"] - o["x"], c["y"] - o["y"]) > cfg["nms_distance"] or abs((c["heading_deg"] - o["heading_deg"] + 180) % 360 - 180) > cfg["nms_heading_deg"] for o in out):
            out.append(c)
    return out


def arm_for(stance, resolution=STANCE_CFG["score_resolution"]):
    """Gives the arm the demo generator uses at a stance: the arm with the better reach score, the scores rounded to `resolution` so that near-ties go to the left arm.

    Args:
        stance (dict): A stance from find_stances ("score_left" and "score_right", None for an arm that does not reach).
        resolution (float): The rounding step, metres. Defaults to STANCE_CFG["score_resolution"] (1 cm).

    Returns:
        str: "left" or "right".

    Raises:
        ValueError: If neither arm reaches.
    """
    sl, sr = stance["score_left"], stance["score_right"]
    if sl is None and sr is None:
        raise ValueError("neither arm reaches at this stance")
    if sr is None:
        return "left"
    if sl is None:
        return "right"
    return "right" if round(sr / resolution) > round(sl / resolution) else "left"
