"""Hand load from the arm's joint torques at a standstill (gravity compensation step 2, MEASUREMENT ONLY, decisions-log M186).

Code generated by Claude

Ground rule (David, Oct 26): nothing here may read an object's mass. The inputs are what the real robot has: the measured joint angles (`qpos`), the torque the motors applied (averaged over a still
window), and the arm's own gravity torque from the robot's model (src/gravity_ff.py: the arm's own bodies only). The true mass of the held object is used afterwards, by the test, as an answer key.

Method
  extra torque = applied motor torque - the arm's own gravity torque            (7 joints of one arm)
  The load at the hand is a force at the pad centre. The hanging weight W (straight down) loads the joints with -Jp^T (0, 0, -W) where Jp is the pad centre's translational Jacobian over the
  arm's 7 joints, so the motors must give W Jz, with Jz the Jacobian's vertical row. Least squares: W = (Jz . extra) / (Jz . Jz), mass = W / g.
  Sanity fit: a force in any direction, f = -lstsq(Jp^T, extra); its angle from straight down, and the share of the extra torque each fit leaves unexplained (norm of the residual over the norm of the
  extra torque). A poor fit means something besides a hanging weight (contact), or a load whose moment about the pad centre matters (the fit has no couple).
"""

import mujoco
import numpy as np

G = 9.81


def reading_status(speeds, trigger_t, now, speed_thr, window_s, max_wait_s, rate_hz):
    """Decides, at one tick, whether the hand-load reading can be taken at a handoff (decisions-log M192).

    The reading needs the arm still: the largest joint speed of each of the last `window_s` seconds below `speed_thr`. It must also come soon after the handoff: if the arm is not still within
    `max_wait_s` of the handoff, the answer is "no reading" (a reading taken later, in the next move, is not the weight at the handoff). The window may reach back before the handoff, as it did
    when the arm was already still.

    Args:
        speeds (sequence of float): The largest absolute joint speed (rad/s) of the arm at each tick up to now, the last one being now.
        trigger_t (float): Time of the handoff (s).
        now (float): Time of the last tick (s).
        speed_thr (float): Still means below this speed (rad/s).
        window_s (float): Length of the still window (s).
        max_wait_s (float): Longest wait after the handoff (s), WEIGHT_READING_CFG["max_wait_s"].
        rate_hz (float): Ticks per second of `speeds`.

    Returns:
        str: "take" (the arm is still now and it is in time), "wait" (not still yet, still in time) or "no reading" (out of time).
    """
    n = int(round(window_s * rate_hz))
    late = now - trigger_t > max_wait_s
    still = len(speeds) >= n and all(abs(v) < speed_thr for v in list(speeds)[-n:])
    if still and not late:
        return "take"
    return "no reading" if late or now - trigger_t >= max_wait_s else "wait"


def hand_load(model, qpos, applied7, arm, gff):
    """Fits the load at the pad centre of one arm.

    Args:
        model (mujoco.MjModel): The compiled model.
        qpos (numpy.ndarray): The measured generalized positions (full qpos, a still-window average).
        applied7 (numpy.ndarray): The applied motor torque of the arm's 7 joints (N m), a still-window average.
        arm (src.mink_arm.MinkArm): The arm (its pad centre, `qadr`, `vadr`, `tcp`).
        gff (src.gravity_ff.ArmGravityFeedforward): The arm's own gravity torque; its first 7 values are the LEFT arm's (sides order left, right).

    Returns:
        dict: "extra_nm" (7,), "weight_n", "mass_kg" (the straight-down fit), "unexplained_down", "free_force_n" (3,), "free_mag_n", "angle_from_down_deg", "unexplained_free".
    """
    d = mujoco.MjData(model)
    d.qpos[:] = qpos
    mujoco.mj_kinematics(model, d)
    mujoco.mj_comPos(model, d)
    tau_g = gff.torques(d)[:7]
    extra = np.asarray(applied7, float) - tau_g
    point, _ = arm.pad_pose(d)
    jacp = np.zeros((3, model.nv))
    mujoco.mj_jac(model, d, jacp, None, point, arm.tcp)
    J = jacp[:, arm.vadr]                                   # (3, 7)
    jz = J[2]
    W = float(jz @ extra / (jz @ jz))
    n = max(float(np.linalg.norm(extra)), 1e-12)
    f_load = -np.linalg.lstsq(J.T, extra, rcond=None)[0]    # the force the load puts on the hand (any direction)
    mag = float(np.linalg.norm(f_load))
    ang = float(np.degrees(np.arccos(np.clip(-f_load[2] / max(mag, 1e-12), -1.0, 1.0))))
    return {"extra_nm": extra, "weight_n": W, "mass_kg": W / G, "unexplained_down": float(np.linalg.norm(extra - W * jz) / n), "free_force_n": f_load, "free_mag_n": mag,
            "angle_from_down_deg": ang, "unexplained_free": float(np.linalg.norm(extra + J.T @ f_load) / n), "pad_point": point}


def hand_load_with_balance_point(model, qpos, applied7, arm, gff):
    """Weight and balance point of the load from the same extra torques (measurement only, as `hand_load`).

    A weight W straight down acting at a point a (world vector from the pad centre) loads the joints with -J(p+a)^T (0, 0, -W). Moving the point by a changes the translational Jacobian by -[a]x Jr
    (Jr the rotational Jacobian), so the motors must give  extra = W Jp_z - m^T Jr  with m = W (z x a) = W (-a_y, a_x, 0). That is linear in (W, m_x, m_y): three numbers. The vertical part of the
    balance point a_z does not enter at all (a force along its own line of action gives the same joint torques wherever it is applied along that line), so it cannot be found from the torques at one
    pose (nor at any two poses with the hand level); it is returned as None. The horizontal offset (a_x, a_y) = (m_y, -m_x) / W is returned in the world and, with a_z set to 0, in the pad frame.
    Inputs and the ground rule are those of `hand_load`: no mass or centre of mass is read.

    Returns:
        dict: "weight_n", "mass_kg", "offset_world_xy_m" (a_x, a_y), "offset_pad_frame_m" (3, with a_z = 0), "a_z" None, "unexplained" (norm of the residual over the norm of the extra torque, this fit),
        "unexplained_down_only" (the one-number fit, for comparison), "extra_nm" (7,), "pad_rot" (3, 3).
    """
    d = mujoco.MjData(model)
    d.qpos[:] = qpos
    mujoco.mj_kinematics(model, d)
    mujoco.mj_comPos(model, d)
    tau_g = gff.torques(d)[:7]
    extra = np.asarray(applied7, float) - tau_g
    point, R = arm.pad_pose(d)
    jp, jr = np.zeros((3, model.nv)), np.zeros((3, model.nv))
    mujoco.mj_jac(model, d, jp, jr, point, arm.tcp)
    Jp, Jr = jp[:, arm.vadr], jr[:, arm.vadr]
    n = max(float(np.linalg.norm(extra)), 1e-12)
    jz = Jp[2]
    W1 = float(jz @ extra / (jz @ jz))
    A = np.stack([Jp[2], -Jr[0], -Jr[1]], axis=1)             # (7, 3): columns for W, m_x, m_y
    x, *_ = np.linalg.lstsq(A, extra, rcond=None)
    W, mx, my = (float(v) for v in x)
    ax, ay = (my / W, -mx / W) if abs(W) > 1e-9 else (float("nan"), float("nan"))
    a_world = np.array([ax, ay, 0.0])
    return {"weight_n": W, "mass_kg": W / G, "offset_world_xy_m": [ax, ay], "offset_pad_frame_m": [float(v) for v in R.T @ a_world], "a_z": None,
            "unexplained": float(np.linalg.norm(extra - A @ x) / n), "unexplained_down_only": float(np.linalg.norm(extra - W1 * jz) / n), "mass_down_only_kg": W1 / G,
            "extra_nm": extra, "pad_rot": R, "pad_point": point}
