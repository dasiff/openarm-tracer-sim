"""Imports the updated OpenArm robot description (B1c) into this simulation: fetches the pinned sources, expands the URDF, and generates the robot file models/robot/combined_robot.xml.

Code generated by Claude

    python tools/import_openarm_description.py [--expand-only] [--cache data/import_cache]

Reproducible: nothing is edited by hand. The sources are pinned by commit (below); the fetched repositories, a small virtual environment with xacro and the expanded URDF live in the cache
directory (git-ignored). The generated files, which ARE committed, are
    models/robot/combined_robot.xml        the robot (Tracer base, one-joint pedestal, torso, both arms with hands and fingers) for the scenes to include
    models/robot/openarm_v1_reference.json the numbers of the expanded URDF (masses, centres of mass, inertias, joint axes, origins, limits) that experiments/robot_vs_urdf_test.py checks the
                                           compiled model against

What the generator does (see generate()):
  * the base is deps/OpenArm-Combined/combined_robot.xml (a submodule: read, never edited): the Tracer, the materials, the default classes, the visual and collision meshes of the arms;
  * the pedestal becomes one slide joint (the description's pedestal: torso 0.3048 m above the pedestal base, travel 0 to 0.418 m); the description has no masses or collision shapes for it, so
    ours (the old estimates and boxes) are used;
  * every arm link, the hand and the fingers take their frames, masses, centres of mass, inertia tensors and joint limits from the expanded URDF (this fixes the old right arm's link7 centre of mass);
  * the hand is attached to link7 directly (the old link8 is gone), the tool point, the finger positions and the finger collision geometry (with the right hand's mirrored finger mesh) come from the URDF.
The arm gains and the one-actuator gripper are not in the robot file: src/arm_actuators.py and src/robot_specs.py add them at load time, as before.
"""

import argparse
import json
import subprocess
import sys
import textwrap
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Pinned sources
SOURCES = {
    "openarm_description": ("https://github.com/enactic/openarm_description.git", "1fba2cbc05001f05b4514120b70130b4ac06f409"),       # enactic, "1.0" line (upstream.repos.lock of mobile_bimanual_ros2)
    "mobile_bimanual_ros2": ("https://github.com/Luke-kC/mobile_bimanual_ros2.git", "74ce18e"),                                      # the pedestal and the arm mounts (the description's pedestal_openarm xacro)
}
XACRO_FILE = "src/mobile_bimanual_description/urdf/pedestal_openarm.urdf.xacro"

# The pedestal numbers of that xacro (pedestal.urdf.xacro and pedestal_openarm.urdf.xacro): one prismatic joint, collapsed height 0.3048 m, travel 0 to 0.418 m; the torso (openarm_body_link0)
# is mounted on the moving link's origin. The description gives no masses or collision shapes for the pedestal.
PEDESTAL = {"collapsed_height": 0.3048, "travel": 0.418, "base_box": 0.12, "plate_box": 0.14, "plate_thickness": 0.02}


def run(cmd, **kw):
    print("  $", " ".join(str(c) for c in cmd), flush=True)
    subprocess.run([str(c) for c in cmd], check=True, **kw)


def fetch(cache):
    """Clones the pinned repositories into the cache (once) and checks out the pinned commits. Returns {name: path}."""
    cache.mkdir(parents=True, exist_ok=True)
    out = {}
    for name, (url, commit) in SOURCES.items():
        path = cache / name
        if not path.exists():
            run(["git", "clone", "-q", url, path])
        run(["git", "-C", path, "checkout", "-q", commit])
        out[name] = path
    return out


def xacro_env(cache):
    """Makes the small virtual environment that runs xacro and the stub of the ROS 2 package lookup xacro needs for $(find ...). Returns (python path, stub directory)."""
    venv = cache / "venv"
    py = venv / "bin" / "python"
    if not py.exists():
        run([sys.executable, "-m", "venv", venv])
        run([py, "-m", "pip", "install", "-q", "xacro", "pyyaml"])
    stub = cache / "stubs" / "ament_index_python"
    stub.mkdir(parents=True, exist_ok=True)
    (stub / "__init__.py").write_text('"""Stub of ament_index_python (not on PyPI): $(find pkg) looks the package up in the environment variable STUB_PACKAGES (name=path pairs)."""\n')
    (stub / "packages.py").write_text(textwrap.dedent('''
        import os


        class PackageNotFoundError(KeyError):
            pass


        def get_package_share_directory(name):
            for item in os.environ.get("STUB_PACKAGES", "").split(os.pathsep):
                n, _, path = item.partition("=")
                if n == name:
                    return path
            raise PackageNotFoundError(name)
    '''))
    return py, cache / "stubs"


def expand(cache, repos):
    """Expands the xacro of the description's pedestal and bimanual OpenArm into a URDF in the cache. Returns its path."""
    py, stubs = xacro_env(cache)
    out = cache / "expanded_pedestal_openarm.urdf"
    desc = repos["openarm_description"]
    mbr_desc = repos["mobile_bimanual_ros2"] / "src" / "mobile_bimanual_description"
    env = {"PATH": "/usr/bin:/bin", "PYTHONPATH": str(stubs), "STUB_PACKAGES": f"openarm_description={desc}:mobile_bimanual_description={mbr_desc}"}
    run([cache / "venv" / "bin" / "xacro", repos["mobile_bimanual_ros2"] / XACRO_FILE, "-o", out], env=env)
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("--expand-only", action="store_true", help="fetch and expand, do not generate")
    ap.add_argument("--cache", default=str(ROOT / "data" / "import_cache"))
    args = ap.parse_args()
    cache = Path(args.cache)
    repos = fetch(cache)
    urdf = expand(cache, repos)
    print(f"expanded URDF: {urdf} ({urdf.stat().st_size} bytes)")
    if args.expand_only:
        return
    from tools.openarm_import_generate import generate
    generate(ROOT, cache, urdf, repos, PEDESTAL)


if __name__ == "__main__":
    sys.path.insert(0, str(ROOT))
    main()
