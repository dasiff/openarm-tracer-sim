"""The generator half of tools/import_openarm_description.py: turns the expanded URDF and the base robot file into models/robot/combined_robot.xml (see that file's docstring).

Code generated by Claude

generate(root, cache, urdf_path, repos, pedestal) reads
    the base robot file   deps/OpenArm-Combined/combined_robot.xml (never edited): the Tracer, materials, default classes, mesh assets, the torso and arm visuals,
    the expanded URDF     the arm mounts, the joint origins, axes and limits, the inertials, the visual and collision origins and mesh scales, the hand, the tool point and the fingers,
and writes
    models/robot/combined_robot.xml and models/robot/openarm_v1_reference.json (atomically: a temporary file, then a rename).

Mirrored meshes: a URDF mesh scale with a negative y (the left arm's links, the "right_finger" of every hand) is a mirrored copy of a mesh. MuJoCo's own URDF import places such a mesh
wrongly (the right finger ended up beside its hand), so here the mirror is made as a separate mesh asset with scale "0.001 -0.001 0.001", as the base file already does, and the geom
gets the URDF's origin offset unchanged.
"""

import copy
import json
import math
import os
import re
import xml.etree.ElementTree as ET
from pathlib import Path

import numpy as np

G_PEDESTAL_COLOR = "0.55 0.57 0.60 1"
PEDESTAL_DAMPING = 50000.0      # N s/m: the old coupled pair's 800 + 50000, so the lift keeps its old speed for a given force
LINKS = tuple(f"link{i}" for i in range(8))


def fmt(v):
    return " ".join(f"{float(x):.10g}" for x in v)


def rpy_quat(rpy):
    """Quaternion (w, x, y, z) of a URDF rpy (fixed axes x, y, z: R = Rz Ry Rx)."""
    r, p, y = rpy
    cr, sr, cp, sp, cy, sy = math.cos(r / 2), math.sin(r / 2), math.cos(p / 2), math.sin(p / 2), math.cos(y / 2), math.sin(y / 2)
    q = np.array([cr * cp * cy + sr * sp * sy, sr * cp * cy - cr * sp * sy, cr * sp * cy + sr * cp * sy, cr * cp * sy - sr * sp * cy])
    return q / np.linalg.norm(q)


def floats(s):
    return [float(x) for x in s.split()]


def parse_urdf(path):
    """Reads links (mass, centre of mass, inertia, visual and collision origins and mesh scales) and joints of the URDF.

    Returns:
        dict: {"links": {name: {...}}, "joints": {name: {...}}}; inertia is [ixx, iyy, izz, ixy, ixz, iyz]. The file is only parsed, never executed.
    """
    root = ET.parse(path).getroot()
    links, joints = {}, {}
    for l in root.findall("link"):
        d = {}
        i = l.find("inertial")
        if i is not None:
            o, n = i.find("origin"), i.find("inertia")
            assert o is None or floats(o.get("rpy", "0 0 0")) == [0, 0, 0], f"{l.get('name')}: inertial frame is rotated"
            d.update(mass=float(i.find("mass").get("value")), com=floats(o.get("xyz")) if o is not None else [0.0] * 3,
                     inertia=[float(n.get(k)) for k in ("ixx", "iyy", "izz", "ixy", "ixz", "iyz")])
        for kind in ("visual", "collision"):
            v = l.find(kind)
            if v is not None:
                g, o = v.find("geometry")[0], v.find("origin")
                d[kind] = {"shape": g.tag, "origin": floats(o.get("xyz")) if o is not None else [0.0] * 3,
                           "mesh": os.path.basename(g.get("filename", "")), "scale": floats(g.get("scale", "1 1 1")), "size": floats(g.get("size", "0"))}
        links[l.get("name")] = d
    for j in root.findall("joint"):
        o, a, lim = j.find("origin"), j.find("axis"), j.find("limit")
        joints[j.get("name")] = {"type": j.get("type"), "parent": j.find("parent").get("link"), "child": j.find("child").get("link"),
                                 "xyz": floats(o.get("xyz")), "rpy": floats(o.get("rpy")), "axis": floats(a.get("xyz")) if a is not None else None,
                                 "limit": [float(lim.get("lower")), float(lim.get("upper")), float(lim.get("effort")), float(lim.get("velocity"))] if lim is not None else None,
                                 "mimic": j.find("mimic").get("joint") if j.find("mimic") is not None else None}
    return {"links": links, "joints": joints}


def inertial_el(mass, com, inertia):
    e = ET.Element("inertial", pos=fmt(com), mass=f"{mass:.10g}", fullinertia=fmt(inertia))
    return e


def shift_inertia(mass, com, inertia, new_com):
    """Inertia tensor (3x3) of a body about `new_com` (parallel axis theorem), given the one about its centre of mass `com`."""
    d = np.asarray(com) - np.asarray(new_com)
    return inertia + mass * (np.dot(d, d) * np.eye(3) - np.outer(d, d))


def full(m):
    return [m[0, 0], m[1, 1], m[2, 2], m[0, 1], m[0, 2], m[1, 2]]


def mat(i6):
    ixx, iyy, izz, ixy, ixz, iyz = i6
    return np.array([[ixx, ixy, ixz], [ixy, iyy, iyz], [ixz, iyz, izz]])


class Assets:
    """The mesh assets of the generated file: the base file's, plus the mirrored copies the URDF asks for."""

    def __init__(self, asset_el):
        self.el = asset_el
        self.by_name = {m.get("name"): m for m in asset_el.findall("mesh")}

    def get(self, base, flip):
        """Name of the asset for the mesh `base` (an existing asset name, unmirrored), mirrored in y if `flip`."""
        src = self.by_name[base]
        assert [float(x) for x in src.get("scale").split()][1] > 0, f"{base} is itself mirrored"
        if not flip:
            return base
        name = re.sub(r"(\.obj)?$", lambda m: "_flip" + (m.group(0) or ""), base, count=1)
        if name not in self.by_name:
            el = copy.deepcopy(src)
            el.set("name", name)
            sx, sy, sz = (float(x) for x in src.get("scale").split())
            el.set("scale", fmt([sx, -sy, sz]))
            src_i = list(self.el).index(src)
            self.el.insert(src_i + 1, el)
            self.by_name[name] = el
        return name


def unmirrored(mesh_name):
    """The unmirrored asset name of a base file mesh name (strips a trailing _left or _flip)."""
    return re.sub(r"_(left|flip)(?=(\.obj)?$)", "", mesh_name)


def build_pedestal(base_root, ped, bodies):
    """Builds the one-joint pedestal: a fixed base body and a moving body (the torso's frame), from the old estimated masses and the description's dimensions."""
    old = {n: bodies[n] for n in ("pedestal_Bottom", "pedestal_Middle", "pedestal_Top")}

    def inertial_of(b):
        i = b.find("inertial")
        return float(i.get("mass")), np.array(floats(i.get("pos"))), mat(floats(i.get("fullinertia"))[:3] + [0, 0, 0]) if i.get("fullinertia") else None

    mb, cb, Ib = inertial_of(old["pedestal_Bottom"])
    mm, cm, Im = inertial_of(old["pedestal_Middle"])
    mt, ct, It = inertial_of(old["pedestal_Top"])
    top_z_old = 0.75                                                      # the torso's height above the deck in the old file, fully raised
    cm_rel, ct_rel = cm - np.array([0, 0, top_z_old]), ct - np.array([0, 0, top_z_old])
    m_move = mm + mt
    c_move = (mm * cm_rel + mt * ct_rel) / m_move
    I_move = shift_inertia(mm, cm_rel, Im, c_move) + shift_inertia(mt, ct_rel, It, c_move)

    h, travel = ped["collapsed_height"], ped["travel"]
    raised = h + travel
    base = ET.Element("body", name="pedestal_base", pos="0 0 0")
    base.append(inertial_el(mb, cb, full(Ib)))
    box = ped["base_box"]
    ET.SubElement(base, "geom", name="pedestal_base_collision", type="box", size=fmt([box / 2, box / 2, h / 2]), pos=fmt([0, 0, h / 2]), attrib={"class": "collision"})
    ET.SubElement(base, "geom", name="pedestal_base_visual", type="box", size=fmt([box / 2, box / 2, h / 2]), pos=fmt([0, 0, h / 2]), rgba=G_PEDESTAL_COLOR, attrib={"class": "visual"})
    # The moving body: its origin is the torso's origin (the top of the pedestal). The XML position is the raised one, with the joint's reference at the raised value, so the model starts
    # raised (the old file's start) and the joint value is the height above the collapsed pedestal (0 to 0.418 m), as the description's pedestal_joint.
    top = ET.SubElement(base, "body", name="pedestal_top", pos=fmt([0, 0, raised]))
    ET.SubElement(top, "joint", name="pedestal_joint", type="slide", axis="0 0 1", range=fmt([0.0, travel]), ref=f"{travel:.10g}", limited="true", damping=f"{PEDESTAL_DAMPING:g}")
    top.append(inertial_el(m_move, c_move, full(I_move)))
    plate_t, plate = ped["plate_thickness"], ped["plate_box"]
    ET.SubElement(top, "geom", name="pedestal_top_collision", type="box", size=fmt([plate / 2, plate / 2, plate_t / 2]), pos=fmt([0, 0, -plate_t / 2]), attrib={"class": "collision"})
    ET.SubElement(top, "geom", name="pedestal_top_visual", type="box", size=fmt([plate / 2, plate / 2, plate_t / 2]), pos=fmt([0, 0, -plate_t / 2]), rgba=G_PEDESTAL_COLOR,
                  attrib={"class": "visual"})
    # The sliding column, drawn only: it slides inside the fixed box (the real one telescopes), from the base's top down to the plate.
    col_w, col_h = box - 0.02, h - plate_t
    ET.SubElement(top, "geom", name="pedestal_column_visual", type="box", size=fmt([col_w / 2, col_w / 2, col_h / 2]), pos=fmt([0, 0, -plate_t - col_h / 2]),
                  rgba="0.72 0.74 0.78 1", attrib={"class": "visual"})
    return base, top, dict(mass_fixed=mb, mass_moving=m_move, com_moving=c_move.tolist(), inertia_moving=full(I_move))


def generate(root, cache, urdf_path, repos, ped):
    root = Path(root)
    base_path = root / "deps" / "OpenArm-Combined" / "combined_robot.xml"
    out_dir = root / "models" / "robot"
    out_dir.mkdir(parents=True, exist_ok=True)
    tree = ET.parse(base_path)
    mj = tree.getroot()
    U = parse_urdf(urdf_path)
    J, L = U["joints"], U["links"]

    compiler = mj.find("compiler")
    rel = os.path.relpath(root / "deps" / "OpenArm-Combined", out_dir)
    compiler.set("meshdir", rel)
    # The description's finger inertia (ixx = iyy = 2.375e-6, izz = 7.5e-7, products of inertia 1e-6) is not a physical inertia tensor: its principal moments break the triangle
    # inequality MuJoCo checks. balanceinertia lets MuJoCo raise the smallest moment to the nearest valid value (a few 1e-7 kg m^2 on a 36 g finger; the test reports the change).
    compiler.set("balanceinertia", "true")
    assets = Assets(mj.find("asset"))

    wb = mj.find("worldbody")
    parent_of = {c: p for p in wb.iter() for c in p}
    bodies = {b.get("name"): b for b in wb.iter("body")}
    base_link = bodies["base_link"]

    # --- pedestal: one slide joint -----------------------------------------------------------------------------------------------------------------------------------------------------
    old_bottom = bodies["pedestal_Bottom"]
    torso = bodies["openarm_body_link0"]
    ped_base, ped_top, ped_info = build_pedestal(mj, ped, bodies)
    base_link.insert(list(base_link).index(old_bottom), ped_base)
    base_link.remove(old_bottom)
    torso.set("pos", "0 0 0")
    torso.set("quat", "1 0 0 0")
    ped_top.append(torso)
    for name in ("pedestal_Bottom", "pedestal_Middle", "pedestal_Top"):
        for m in mj.find("asset").findall("mesh"):
            if m.get("name") == name:
                mj.find("asset").remove(m)

    # --- arms: frames, inertials, limits, mesh mirroring from the URDF -----------------------------------------------------------------------------------------------------------------
    ref = {"links": {}, "joints": {}}
    for side in ("left", "right"):
        mount = J[f"openarm_{side}_openarm_body_link0_joint"]
        jn = {0: mount}
        for i in range(1, 8):
            jn[i] = J[f"openarm_{side}_joint{i}"]
        for i in range(8):
            b = bodies[f"openarm_{side}_link{i}"]
            j = jn[i]
            b.set("pos", fmt(j["xyz"]))
            b.set("quat", fmt(rpy_quat(j["rpy"])))
            lk = L[f"openarm_{side}_link{i}"]
            old_in = b.find("inertial")
            new_in = inertial_el(lk["mass"], lk["com"], lk["inertia"])
            b.insert(list(b).index(old_in), new_in)
            b.remove(old_in)
            if i >= 1:
                je = b.find("joint")
                je.set("axis", fmt(j["axis"]))
                je.set("range", fmt(j["limit"][:2]))
            for g in b.findall("geom"):
                kind = "collision" if g.get("name").endswith("_collision") else "visual"
                spec = lk[kind]
                g.set("pos", fmt(spec["origin"]))
                g.attrib.pop("quat", None)
                flip = spec["scale"][1] < 0
                g.set("mesh", assets.get(unmirrored(g.get("mesh")), flip))
            ref["links"][f"openarm_{side}_link{i}"] = lk
            ref["joints"][f"openarm_{side}_link{i}" if i == 0 else f"openarm_{side}_joint{i}"] = j

        # --- hand, tool point, fingers: link8 is gone, the hand hangs on link7 -----------------------------------------------------------------------------------------------------------
        link7 = bodies[f"openarm_{side}_link7"]
        old8 = bodies[f"openarm_{side}_link8"]
        old_hand = bodies[f"openarm_{side}_hand"]
        link7.remove(old8)
        hj, tj = J[f"openarm_{side}_hand_joint"], J[f"openarm_{side}_hand_tcp_joint"]
        hl = L[f"openarm_{side}_hand"]
        hand = ET.SubElement(link7, "body", name=f"openarm_{side}_hand", pos=fmt(hj["xyz"]))
        hand.append(inertial_el(hl["mass"], hl["com"], hl["inertia"]))
        # geoms of the old hand (names, classes, materials), moved to the URDF origin
        for g in old_hand.findall("geom"):
            g2 = copy.deepcopy(g)
            g2.set("pos", fmt(hl["collision" if g.get("name").endswith("_collision") else "visual"]["origin"]))
            g2.attrib.pop("quat", None)
            hand.append(g2)
        ET.SubElement(hand, "body", name=f"openarm_{side}_hand_tcp", pos=fmt(tj["xyz"]))
        for k, fname in ((1, "right_finger"), (2, "left_finger")):
            fj = J[f"openarm_{side}_finger_joint{k}"]
            fl = L[f"openarm_{side}_{fname}"]
            old_f = bodies[f"openarm_{side}_{fname}"]
            fb = ET.SubElement(hand, "body", name=f"openarm_{side}_{fname}", pos=fmt(np.array(fj["xyz"]) - np.array(hj["xyz"])))
            je = copy.deepcopy(old_f.find("joint"))
            je.set("axis", fmt(fj["axis"]))
            je.set("range", fmt(fj["limit"][:2]))
            fb.append(je)
            fb.append(inertial_el(fl["mass"], fl["com"], fl["inertia"]))
            for g in old_f.findall("geom"):
                g2 = copy.deepcopy(g)
                kind = "collision" if g.get("name").endswith("_collision") else "visual"
                g2.set("pos", fmt(fl[kind]["origin"]))
                g2.attrib.pop("quat", None)
                g2.set("mesh", assets.get(unmirrored(g.get("mesh")), fl[kind]["scale"][1] < 0))
                fb.append(g2)
            ref["joints"][f"openarm_{side}_finger_joint{k}"] = fj
            ref["links"][f"openarm_{side}_{fname}"] = fl
        ref["links"][f"openarm_{side}_hand"] = hl
        ref["joints"][f"openarm_{side}_hand_joint"] = hj
        ref["joints"][f"openarm_{side}_hand_tcp_joint"] = tj

    # --- contacts ----------------------------------------------------------------------------------------------------------------------------------------------------------------------------
    contact = mj.find("contact")
    for e in list(contact):
        names = {e.get("body1"), e.get("body2")}
        if any(n in names for n in ("pedestal_Bottom", "pedestal_Middle", "pedestal_Top")) or any("link8" in n for n in names):
            contact.remove(e)
    # the old file's pedestal stack: Tracer, base, moving part, torso (and the base against the torso, which the description's fixed mount makes rigid at the collapsed height)
    for b1, b2 in (("base_link", "pedestal_base"), ("pedestal_base", "pedestal_top"), ("pedestal_top", "openarm_body_link0"), ("pedestal_base", "openarm_body_link0")):
        ET.SubElement(contact, "exclude", body1=b1, body2=b2)

    # --- actuators and equalities: one actuator per hand, on finger_joint1 (finger_joint2 follows through the equality) -----------------------------------------------------------------
    act = mj.find("actuator")
    for a in list(act):
        n = a.get("name")
        if n.endswith("_finger2_ctrl"):
            act.remove(a)
        elif n.endswith("_finger1_ctrl"):
            side = n.split("_")[0]
            new = ET.Element("position", name=f"{side}_gripper_ctrl", joint=a.get("joint"), attrib={"class": "motor_finger"})
            act.insert(list(act).index(a), new)
            act.remove(a)

    # --- prune unused mesh assets ------------------------------------------------------------------------------------------------------------------------------------------------------
    used = {g.get("mesh") for g in mj.iter("geom") if g.get("mesh")}
    for m in list(mj.find("asset").findall("mesh")):
        if m.get("name") not in used:
            mj.find("asset").remove(m)

    mj.set("model", "tracer_pedestal_openarm_v1")
    ET.indent(tree, space="  ")
    header = ("<!-- GENERATED by tools/import_openarm_description.py: do not edit by hand, rerun the script.\n"
              f"     Sources: base file deps/OpenArm-Combined/combined_robot.xml (Tracer, materials, meshes); updated description: enactic/openarm_description {repos['openarm_description'].name} "
              "pinned at 1fba2cbc05001f05b4514120b70130b4ac06f409 and Luke-kC/mobile_bimanual_ros2 pedestal_openarm at 74ce18e. -->\n")
    text = header + ET.tostring(mj, encoding="unicode") + "\n"
    out = out_dir / "combined_robot.xml"
    tmp = out_dir / "combined_robot.xml.tmp"
    tmp.write_text(text)
    ET.parse(tmp)                                                   # must still parse
    os.replace(tmp, out)

    ref["pedestal"] = dict(ped, **ped_info, raised_height=ped["collapsed_height"] + ped["travel"])
    ref["sources"] = {"openarm_description": "1fba2cbc05001f05b4514120b70130b4ac06f409", "mobile_bimanual_ros2": "74ce18e"}
    tmpj = out_dir / "openarm_v1_reference.json.tmp"
    tmpj.write_text(json.dumps(ref, indent=1, sort_keys=True) + "\n")
    json.loads(tmpj.read_text())
    os.replace(tmpj, out_dir / "openarm_v1_reference.json")
    print(f"wrote {out} and {out_dir / 'openarm_v1_reference.json'}")
